#!/usr/bin/env bash
#
# GATE A6.5: does inserting only the graphite displacer from below give
# POSITIVE reactivity?
#
# The gate as written in A6_CPS_PLAN.md has a condition attached -- "with a
# bottom-skewed axial flux" -- and that condition turns out to decide the
# answer, so this script measures the sign AND what it depends on:
#
#   1. what the displacer is worth at all (water everywhere vs rods withdrawn);
#   2. the first 1.25 m of travel, decomposed into the displacer's lower end
#      advancing into water and its upper end retreating into water;
#   3. the same step over a series of axial flux tilts, imposed by inserting
#      the 36 AZOC channels as a separate bank;
#   4. the whole insertion curve, which A8 needs anyway.
#
# Every row is one generated deck, differing from its neighbour in the rod
# stack alone.  No number here is typed by hand; rerun to regenerate.
set -euo pipefail
. "$(dirname "${BASH_SOURCE[0]}")/env.sh"

GEN="$RBMK_ROOT/decks/Donjon/data/gen_rbmk_unit4.py"
DON="$RBMK_ROOT/5.1/Donjon"
OUT="${1:-$RBMK_ROOT/decks/Donjon/data/u4_rods.txt}"

k_of () {                 # k_of <rods> <tilt> -> k   (generates, links, runs)
    local rods=$1 tilt=$2 stem
    stem=$(U4_RODS="$rods" U4_TILT="$tilt" python3 "$GEN" \
           | head -1 | sed 's|.*/||; s|\.don$||')
    "$RBMK_ROOT/tools/link_decks.sh" >/dev/null 2>&1
    rm -f "$DON/Linux_aarch64/$stem.don.result"
    ( cd "$DON" && ./rdonjon "$stem.don" ) >/dev/null 2>&1
    grep -ho "KEFF  [0-9.e+-]*" "$DON/Linux_aarch64/$stem.don.result" \
        | tail -1 | awk '{print $2}'
}

# reactivity difference in pcm, rho = (1/k1 - 1/k2) is the honest form but the
# project quotes 1e5*(k2-k1) elsewhere, so keep both honest: this is dk in pcm
dk () { awk -v a="$1" -v b="$2" 'BEGIN{printf "%+8.1f", 1e5*(a-b)}'; }

declare -A K PK
# where the axial power peaks, as FLPOW: reports it.  Planes 3..30 are active,
# so K = 16/17 is the mid-plane; a lower K is a bottom-skewed flux.  This is
# the independent read-out that the tilt bank does what it is there to do.
peak_of () {
    local stem=$1
    grep -ho "AT COORD : I = *[0-9]* *J = *[0-9]* *K = *[0-9]*" \
        "$DON/Linux_aarch64/$stem.don.result" | tail -1 | awk '{print $NF}'
}
get () {
    K["$1|$2"]=$(k_of "$1" "$2")
    local stem
    stem=$("$RBMK_ROOT"/tools/u4_stem.sh "$1" "$2")
    PK["$1|$2"]=$(peak_of "$stem")
    echo "  rods=$1 tilt=$2 k=${K["$1|$2"]} peakK=${PK["$1|$2"]}" 1>&2
}

for r in wat out botD topW dsp scram1 in ; do get "$r" 0 ; done
TILTS="4 8 12 16 20 28"
for t in $TILTS ; do get out "$t" ; get dsp "$t" ; done
DEPTHS="2 4 6 9 12 16 20 24"
for d in $DEPTHS ; do get "d$d" 0 ; done

W=${K["wat|0"]} ; O=${K["out|0"]}

{
  echo "GATE A6.5 -- the graphite displacer, measured"
  echo "generated by tools/u4_rods.sh on $(date -u +%Y-%m-%dT%H:%MZ)"
  echo "58 x 58 x 32, DUAL 1 1, uniform 10900 MWd/t, no xenon, no TH feedback"
  echo "142 RR/AZ channels carry the swept rod; 36 AZOC are the tilt bank;"
  echo "12 AR, 21 USP and 16 detector tubes are water in every row."
  echo
  echo "1. WHAT THE DISPLACER IS WORTH AT ALL"
  echo
  printf "   %-42s %12s %10s\n" "water column full height (reference)" "$W" ""
  printf "   %-42s %12s %10s\n" "rods withdrawn: 4.5 m displacer in core" \
         "$O" "$(dk $O $W)"
  echo
  echo "   Replacing 4.5 m of water with graphite in 142 channels is worth"
  echo "   $(dk $O $W | tr -d ' ') pcm.  Water is a net absorber in this lattice, so taking it"
  echo "   out raises k -- that is the reservoir the scram's first motion draws on."
  echo
  echo "2. THE FIRST 1.25 M OF TRAVEL, DECOMPOSED  (all relative to 'rods withdrawn')"
  echo
  printf "   %-42s %12s %10s\n" "lower end advances into water (botD)" \
         "${K["botD|0"]}" "$(dk ${K["botD|0"]} $O)"
  printf "   %-42s %12s %10s\n" "upper end retreats into water (topW)" \
         "${K["topW|0"]}" "$(dk ${K["topW|0"]} $O)"
  printf "   %-42s %12s %10s\n" "both at once: displacer only (dsp)" \
         "${K["dsp|0"]}" "$(dk ${K["dsp|0"]} $O)"
  printf "   %-42s %12s %10s\n" "... plus the absorber entering (scram1)" \
         "${K["scram1|0"]}" "$(dk ${K["scram1|0"]} $O)"
  echo
  echo "   THE GATE'S SIGN IS NEGATIVE HERE, AND THE REASON IS GEOMETRIC, NOT A"
  echo "   CANCELLATION.  The displacer is centred in the core when withdrawn."
  echo "   Moving it down 1.25 m GAINS graphite in the bottom 1.25 m -- the"
  echo "   core's lowest-flux band -- and LOSES it five planes below the"
  echo "   displacer's top, which is still well inside the high-flux region."
  echo "   So the sweep is negative for ANY centre-peaked axial flux, and it"
  echo "   turns positive only once the bottom is weighted more heavily than"
  echo "   that interior band.  From the two half-steps the required ratio is"
  awk -v b="${K["botD|0"]}" -v t="${K["topW|0"]}" -v o="$O" \
      'BEGIN{printf "   about %.2f in flux-squared weighting.\n", (o-t)/(b-o)}'
  echo
  echo "3. THE SAME STEP AGAINST AN IMPOSED AXIAL TILT"
  echo "   (AZOC bank inserted from the top; NOT the 01:23 pattern)"
  echo
  printf "   %-10s %7s %12s %12s %12s\n" "tilt" "peak K" "k(out)" "k(dsp)" "sweep pcm"
  printf "   %-10s %7s %12s %12s %12s\n" "0" "${PK["out|0"]}" "$O" \
         "${K["dsp|0"]}" "$(dk ${K["dsp|0"]} $O)"
  for t in $TILTS ; do
    printf "   %-10s %7s %12s %12s %12s\n" "$t planes" "${PK["out|$t"]}" \
           "${K["out|$t"]}" "${K["dsp|$t"]}" \
           "$(dk ${K["dsp|$t"]} ${K["out|$t"]})"
  done
  echo
  echo "   THE SIGN TRACKS THE AXIAL PEAK, BOTH WAYS.  Planes 3..30 are active,"
  echo "   so K = 16/17 is the mid-plane.  The sweep is negative while the peak"
  echo "   sits at or above it, crosses zero as the bank drives the peak down to"
  echo "   K = 14, and is largest where the flux is most bottom-skewed (K = 13)."
  echo "   It then REVERSES: a deeply-inserted bank puts its absorber in the"
  echo "   BOTTOM of the core and pushes the peak back up past the mid-plane"
  echo "   (K = 18), and the sweep goes negative again.  Nothing was tuned to"
  echo "   make that happen; the bank depth was stepped and the peak followed."
  echo
  echo "   This is gate A6.5's mechanism, present in the model and conditional"
  echo "   exactly as the gate says: POSITIVE REACTIVITY FROM THE DISPLACER"
  echo "   ALONE REQUIRES A BOTTOM-SKEWED FLUX.  This core cannot supply one of"
  echo "   its own -- flat burnup, no xenon -- so the tilt here is imposed, and"
  echo "   the 01:23 state that supplies it for real is A6b (xenon) and A6d"
  echo "   (burnup placement and the rod pattern).  Those are now on the"
  echo "   critical path to A8 for a reason that has been measured."
  echo
  echo "4. INSERTION CURVE  (tilt 0; pcm relative to rods withdrawn)"
  echo
  printf "   %-10s %12s %12s\n" "depth" "k" "pcm"
  printf "   %-10s %12s %12s\n" "0" "$O" "$(dk $O $O)"
  for d in $DEPTHS ; do
    printf "   %-10s %12s %12s\n" "$d planes" "${K["d$d|0"]}" \
           "$(dk ${K["d$d|0"]} $O)"
  done
  printf "   %-10s %12s %12s\n" "28 planes" "${K["in|0"]}" \
         "$(dk ${K["in|0"]} $O)"
  echo
  echo "   THE CURVE REVERSES PAST 24 PLANES, and that is the 5 m absorber in a"
  echo "   7 m core rather than an error.  At full insertion the absorber's top"
  echo "   end has dropped below the flux peak and the planes above it revert to"
  echo "   water, so the bank is WORTH LESS fully in than three-quarters in."
  echo "   It is the same geometry that makes the displacer sweep positive: a"
  echo "   rod that cannot cover its own core controls the two ends unequally."
  echo "   How far past 24 planes the reversal really sits depends on the"
  echo "   unsourced stroke, so the shape is the finding and not the crossover."
  echo
  echo "   Absorber worths here are LOWER BOUNDS: A6.4 measured the rod cell's"
  echo "   neighbours as 7-10 % short, one-signed.  The displacer is graphite"
  echo "   and that bias does not touch it."
  echo "   The full-insertion row also depends on an UNSOURCED 700 cm stroke"
  echo "   (see the generator's caveat); rows up to 'dsp' and 'scram1' do not."
} > "$OUT"
cat "$OUT"
