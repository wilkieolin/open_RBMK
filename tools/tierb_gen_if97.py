#!/usr/bin/env python3
"""Generate tierb/RBMKCore.jl/src/IF97Tables.jl from the freesteam C sources
vendored in DONJON's Utilib (the IF97 THM: uses), so the pure-Julia / GPU
water properties carry exactly freesteam's coefficients -- no transcription.
"""
import hashlib, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "5.1", "Utilib", "src")
OUT = os.path.join(ROOT, "tierb", "RBMKCore.jl", "src", "IF97Tables.jl")

def block(fname, name):
    t = open(os.path.join(SRC, fname)).read()
    m = re.search(name + r"\[\]\s*=\s*\{(.*?)\};", t, re.S)
    return m.group(1), hashlib.md5(t.encode()).hexdigest()

def tuples(body, n):
    rows = re.findall(r"\{([^{}]*)\}", body)
    out = []
    for r in rows:
        v = [x.strip() for x in r.split(",")]
        assert len(v) == n, r
        out.append(v)
    return out

r1, h1 = block("region1.c", "REGION1_GPT_DATA")
r2i, h2 = block("region2.c", "REGION2_GPT_IDEAL_DATA")
r2r, _ = block("region2.c", "REGION2_GPT_RESID_DATA")
t4 = open(os.path.join(SRC, "region4.c")).read()
n4 = re.search(r"REGION4_N\[11\]\s*=\s*\{(.*?)\};", t4, re.S).group(1)
h4 = hashlib.md5(t4.encode()).hexdigest()
R1 = tuples(r1, 3); R2I = tuples(r2i, 2); R2R = tuples(r2r, 3)
N4 = [x.strip() for x in n4.split(",")]
with open(OUT, "w") as f:
    f.write("# GENERATED by tools/tierb_gen_if97.py from 5.1/Utilib/src (freesteam):\n")
    f.write(f"#   region1.c {h1}  region2.c {h2}  region4.c {h4}\n# Do not edit.\n\n")
    f.write("const R1_I = (" + ", ".join(r[0] for r in R1) + ",)\n")
    f.write("const R1_J = (" + ", ".join(r[1] for r in R1) + ",)\n")
    f.write("const R1_N = (" + ", ".join(r[2] for r in R1) + ",)\n")
    f.write("const R2I_J = (" + ", ".join(r[0] for r in R2I) + ",)\n")
    f.write("const R2I_N = (" + ", ".join(r[1] for r in R2I) + ",)\n")
    f.write("const R2R_I = (" + ", ".join(r[0] for r in R2R) + ",)\n")
    f.write("const R2R_J = (" + ", ".join(r[1] for r in R2R) + ",)\n")
    f.write("const R2R_N = (" + ", ".join(r[2] for r in R2R) + ",)\n")
    f.write("const R4_N = (" + ", ".join(N4) + ",)\n")
print(OUT, len(R1), len(R2I), len(R2R), len(N4))
