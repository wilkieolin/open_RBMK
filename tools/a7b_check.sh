#!/usr/bin/env bash
#
# A7b: the coupled core.  Flux -> power -> thermal-hydraulics -> coolant
# density and fuel temperature back into the cross-section interpolation.
#
# It does not finish, and WHY it does not finish is the result.  The A5b
# MULTICOMPO's branch axes were built around a lattice-cell nominal state and
# are too narrow for a real core at both ends:
#
#   DCA  axis 0.72 .. 0.02 g/cm3   THM: computes 0.778 at a 265 C inlet
#   TF   axis 600 .. 2000 K        a low-power channel end sits at 586 K
#
# Neither is a modelling error; both are the operating state falling outside
# the table.  The fix is one more value on each axis, which is 1/7 and 1/n of
# a rebuild A6b needs anyway for xenon.
#
# So this runs the loop with the coolant-density feedback pinned (U4_VOIDFB=0,
# Doppler only), reports the iteration history, and extrapolates the
# geometrically-converging eigenvalue to the limit the TF floor stops it from
# reaching.  No number here is typed by hand.
set -euo pipefail
. "$(dirname "${BASH_SOURCE[0]}")/env.sh"

GEN="$RBMK_ROOT/decks/Donjon/data/gen_rbmk_unit4.py"
DON="$RBMK_ROOT/5.1/Donjon"
OUT="${1:-$RBMK_ROOT/decks/Donjon/data/a7b_check.txt}"

run () {            # run <flow> -> stem
    local stem
    stem=$(U4_THM=1 U4_RODS=out U4_FLOW="$1" U4_VOIDFB=0 python3 "$GEN" \
           | head -1 | sed 's|.*/||; s|\.don$||')
    "$RBMK_ROOT/tools/link_decks.sh" >/dev/null 2>&1
    rm -f "$DON/Linux_aarch64/$stem.don.result"
    ( cd "$DON" && ./rdonjon "$stem.don" ) >/dev/null 2>&1 || true
    echo "$stem"
}

report () {         # report <label> <stem>
    python3 - "$1" "$DON/Linux_aarch64/$2.don.result" <<'PYEOF'
import re, sys
label, path = sys.argv[1], sys.argv[2]
t = open(path, "rb").read().decode("latin1")
it = [(int(a), float(b), float(c)) for a, b, c in re.findall(
      r"ITER\s+(\d+) KEFF\s+([0-9.eE+-]+) ERRT\s+([0-9.eE+-]+)", t)]
print(f"   {label}")
print(f"   {'pass':>6} {'k-eff':>14} {'dk pcm':>9} {'fuel-T err K':>14}")
for n, (i, k, e) in enumerate(it):
    dk = "" if n == 0 else f"{1e5*(k-it[n-1][1]):+9.1f}"
    print(f"   {i:>6} {k:>14.6f} {dk:>9} {e:>14.1f}")
if len(it) >= 4:
    d = [it[n][1] - it[n-1][1] for n in range(1, len(it))]
    r = [d[n] / d[n-1] for n in range(1, len(d))]
    rb = sum(r[-2:]) / len(r[-2:])
    tail = d[-1] * rb / (1 - rb)
    print(f"   contraction ratio {r[-2]:.3f}, {r[-1]:.3f} -> geometric, r = {rb:.3f}")
    print(f"   extrapolated limit k = {it[-1][1] + tail:.6f} "
          f"({1e5*tail:+.1f} pcm beyond the last pass)")
    print(f"   Doppler feedback from the 900 K start: "
          f"{1e5*(it[-1][1] + tail - it[0][1]):+.0f} pcm")
hit = re.search(r"NCRRGR: REAL PARAMETER (\S+)\s+WITH VALUE\s+([0-9.eE+-]+) "
                r"IS OUTSIDE THE DOMAIN", t)
dom = re.search(r"Domain:\s+([0-9.eE+-]+)\s+<->\s+([0-9.eE+-]+)", t)
if hit:
    print(f"   STOPPED: {hit.group(1).strip()} reached {float(hit.group(2)):.4g}, "
          f"axis covers {float(dom.group(1)):.4g} to {float(dom.group(2)):.4g}")
PYEOF
}

S1=$(run prop)
S2=$(run unif)
{
  echo "A7b -- the coupled core, and the two axis ends that stop it"
  echo "generated by tools/a7b_check.sh on $(date -u +%Y-%m-%dT%H:%MZ)"
  echo "58 x 58 x 32, DUAL 1 1, rods withdrawn, uniform 10900 MWd/t, 3200 MWth"
  echo "coolant-density feedback PINNED (U4_VOIDFB=0): Doppler only, because"
  echo "the DCA axis tops out at 0.72 g/cm3 and the real inlet is 0.778."
  echo
  echo "1. FLOW VALVED TO POWER  (U4_FLOW=prop, [D] p.95's 30 t/h at 3100 kW)"
  echo
  report "" "$S1"
  echo
  echo "2. UNIFORM FLOW  (U4_FLOW=unif, the core average of the same scaling)"
  echo
  report "" "$S2"
  echo
  echo "READING IT."
  echo
  echo "THE TWO FLOW CASES AGREE TO 1 pcm, AND THAT IS THE CHECK ON THE PINNING."
  echo "   Valving every channel to its own power and giving every channel the"
  echo "   same velocity are very different coolant states, but with the"
  echo "   density feedback pinned the only path from flow to k is cut, so the"
  echo "   two must give the same eigenvalue -- and they do, -240 against"
  echo "   -241 pcm.  Had they differed, the pin would have been leaking."
  echo "   It also means these runs say nothing about the flow distribution;"
  echo "   that question reopens when the DCA axis reaches the inlet."
  echo
  echo "The loop converges, and it converges geometrically -- the fuel"
  echo "temperature error falls by a steady factor each pass and the"
  echo "eigenvalue with it.  The coupling machinery is therefore right: NCR:"
  echo "reads the thermal-hydraulic state back out of the fuel map, MACINI:"
  echo "and TRIVAA: rebuild on it, and FLPOW: feeds THM: in turn."
  echo
  echo "WHAT STOPS IT IS THE CROSS-SECTION TABLE, NOT THE SOLVER.  The A5b"
  echo "MULTICOMPO was built around a lattice-cell nominal state -- coolant"
  echo "0.72 g/cm3, fuel 600-2000 K -- and a real core leaves that box at both"
  echo "ends.  The inlet is subcooled at 0.778 g/cm3, above the DCA axis; the"
  echo "ends of a low-power channel sit near coolant temperature, below the TF"
  echo "axis.  Both are the operating state falling outside the table, and"
  echo "both are one more value on an existing axis."
  echo
  echo "PRICED, so the extension is a decision and not a reflex: pinning the"
  echo "coolant density at 0.72 core-wide costs 103 pcm (dk/dDCA = -0.01779"
  echo "from the 0.60 and 0.72 grid points, extrapolated 0.058 past the axis"
  echo "end), and that is an upper bound because only the subcooled lower part"
  echo "of each channel is above 0.72.  The DCA axis has 7 values, so one more"
  echo "is 1/7 of the branch tensor on a rebuild A6b already needs for xenon."
} > "$OUT"
cat "$OUT"
