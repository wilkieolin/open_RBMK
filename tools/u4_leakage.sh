#!/usr/bin/env bash
#
# A6.5: what the radial reflector is worth in the Unit 4 core, and how much
# its cross sections can matter.
#
# Phase 1b left an open question.  The strip test priced the reflector's
# homogenisation error at 7152 pcm, but measured it on four fuel zones against
# four reflector zones, where the real core is 1661 channels against a
# four-column skin -- an upper bound, not an estimate.  The only way to get
# the core-level number is to measure it in the core, which is what this does.
#
# Every row is a boundary condition or a ring-assignment change applied to the
# SAME generated deck by sed, so nothing but the one thing under test moves.
# No number here is typed by hand; rerun to regenerate.
set -euo pipefail
. "$(dirname "${BASH_SOURCE[0]}")/env.sh"

GEN="$RBMK_ROOT/decks/Donjon/data/gen_rbmk_unit4.py"
DAT="$RBMK_ROOT/decks/Donjon/data"
DON="$RBMK_ROOT/5.1/Donjon"
OUT="${1:-$DAT/u4_leakage.txt}"
BC="X- VOID X+ VOID  Y- VOID Y+ VOID  Z- VOID Z+ VOID"

python3 "$GEN" >/dev/null
U4_REFL=0 python3 "$GEN" >/dev/null

variant () {              # variant <stem> <base> <sed-expr...>
    local stem=$1 base=$2; shift 2
    sed "$@" -e "s/rbmk_unit4_core completed/$stem completed/" \
             -e "s/rbmk_unit4_norefl completed/$stem completed/" \
        "$DAT/$base.don" > "$DAT/$stem.don"
    cp "$DAT/$base.don.access" "$DAT/$stem.don.access"
}

run () {                  # run <stem> -> k
    rm -f "$DON/Linux_aarch64/$1.don.result"
    ( cd "$DON" && ./rdonjon "$1.don" ) >/dev/null 2>&1
    grep -ho "KEFF  [0-9.e+]*" "$DON/Linux_aarch64/$1.don.result" \
        | tail -1 | awk '{print $2}'
}

# boundary-condition rows.  The boundary that matters is NOT the edge of the
# 58 x 58 grid: mixture 0 outside the stack is a virtual volume (USPMIX.f:52)
# and TRIVAC applies the geometry's condition at the real/virtual interface
# instead.  Verified: k is bit-identical for U4_NPAD = 1, 3 and 5.
variant u4lk_refl_void rbmk_unit4_core -e "s/x/x/"
variant u4lk_refl_mirr rbmk_unit4_core \
    -e "s/$BC/X- REFL X+ REFL  Y- REFL Y+ REFL  Z- VOID Z+ VOID/"
variant u4lk_refl_zmir rbmk_unit4_core \
    -e "s/$BC/X- VOID X+ VOID  Y- VOID Y+ VOID  Z- REFL Z+ REFL/"
variant u4lk_bare_void rbmk_unit4_norefl -e "s/x/x/"
variant u4lk_bare_mirr rbmk_unit4_norefl \
    -e "s/$BC/X- REFL X+ REFL  Y- REFL Y+ REFL  Z- VOID Z+ VOID/"
# ring-assignment rows: collapse the depth resolution, or invert it
variant u4lk_ring_all5 rbmk_unit4_core \
    -e "s/MIX 3 FROM 6 /MIX 3 FROM 5 /" -e "s/MIX 4 FROM 7 /MIX 4 FROM 5 /" \
    -e "s/MIX 5 FROM 8 /MIX 5 FROM 5 /"
variant u4lk_ring_all8 rbmk_unit4_core \
    -e "s/MIX 2 FROM 5 /MIX 2 FROM 8 /" -e "s/MIX 3 FROM 6 /MIX 3 FROM 8 /" \
    -e "s/MIX 4 FROM 7 /MIX 4 FROM 8 /"
variant u4lk_ring_rev rbmk_unit4_core \
    -e "s/MIX 2 FROM 5 /MIX 2 FROM 8 /" -e "s/MIX 3 FROM 6 /MIX 3 FROM 7 /" \
    -e "s/MIX 4 FROM 7 /MIX 4 FROM 6 /" -e "s/MIX 5 FROM 8 /MIX 5 FROM 5 /"

"$RBMK_ROOT/tools/link_decks.sh" >/dev/null 2>&1

declare -A K
for s in u4lk_refl_void u4lk_refl_mirr u4lk_refl_zmir u4lk_bare_void \
         u4lk_bare_mirr u4lk_ring_all5 u4lk_ring_all8 u4lk_ring_rev ; do
    K[$s]=$(run $s)
    echo "  $s ${K[$s]}" 1>&2
done

pcm () { awk -v a="$1" -v b="$2" 'BEGIN{printf "%+8.1f", 1e5*(a-b)}'; }
REF=${K[u4lk_refl_void]}

{
  echo "A6.5 -- radial reflector worth and sensitivity, Unit 4 core"
  echo "generated by tools/u4_leakage.sh on $(date -u +%Y-%m-%dT%H:%MZ)"
  echo "58 x 58 x 32, DUAL 1 1, uniform 10900 MWd/t, all rods withdrawn"
  echo
  printf "%-36s %12s %10s\n" "case" "k-eff" "pcm vs ref"
  printf "%-36s %12s %10s\n" "------------------------------------" \
         "------------" "----------"
  printf "%-36s %12s %10s   <- reference\n" \
         "4 graphite rings, VOID at stack" "${K[u4lk_refl_void]}" ""
  printf "%-36s %12s %10s\n" "   ... mirror at the stack edge" \
         "${K[u4lk_refl_mirr]}" "$(pcm ${K[u4lk_refl_mirr]} $REF)"
  printf "%-36s %12s %10s\n" "   ... mirror on the axial faces" \
         "${K[u4lk_refl_zmir]}" "$(pcm ${K[u4lk_refl_zmir]} $REF)"
  printf "%-36s %12s %10s\n" "no radial reflector, VOID at core" \
         "${K[u4lk_bare_void]}" "$(pcm ${K[u4lk_bare_void]} $REF)"
  printf "%-36s %12s %10s\n" "   ... mirror at the core edge" \
         "${K[u4lk_bare_mirr]}" "$(pcm ${K[u4lk_bare_mirr]} $REF)"
  printf "%-36s %12s %10s\n" "all 4 rings = zone 5 (inner graph.)" \
         "${K[u4lk_ring_all5]}" "$(pcm ${K[u4lk_ring_all5]} $REF)"
  printf "%-36s %12s %10s\n" "all 4 rings = zone 8 (cooled)" \
         "${K[u4lk_ring_all8]}" "$(pcm ${K[u4lk_ring_all8]} $REF)"
  printf "%-36s %12s %10s\n" "ring order reversed" \
         "${K[u4lk_ring_rev]}" "$(pcm ${K[u4lk_ring_rev]} $REF)"
  echo
  echo "READING IT."
  echo
  echo "The radial reflector is worth $(pcm $REF ${K[u4lk_bare_void]} | tr -d ' ') pcm in this core, and only"
  echo "$(pcm ${K[u4lk_refl_mirr]} $REF | tr -d ' ') pcm leaks past it -- 1 m of graphite is already an almost"
  echo "perfect reflector.  A MIRROR at the core edge is worth $(pcm ${K[u4lk_bare_mirr]} ${K[u4lk_bare_void]} | tr -d ' ') pcm, which"
  echo "is the whole radial leakage.  Those are not in conflict: a mirror sets"
  echo "B_r^2 = 0, while a real reflector only extends the effective radius."
  echo "Diffusion theory with D_r = 0.84, L_r = 54 cm gives a reflector saving"
  echo "of 49 cm on a 590 cm radius; with M^2 = 657 cm^2 read off the"
  echo "mirror-at-core-edge row, that predicts ~155 pcm against the measured"
  echo "$(pcm $REF ${K[u4lk_bare_void]} | tr -d ' ').  The model is behaving."
  echo
  echo "THIS CLOSES THE PHASE 1b OPEN QUESTION.  The band between having no"
  echo "radial reflector at all ($(pcm ${K[u4lk_bare_void]} $REF | tr -d ' ') pcm) and a perfect mirror at the stack"
  echo "edge ($(pcm ${K[u4lk_refl_mirr]} $REF | tr -d ' ') pcm) is the whole room the reflector dataset has to move"
  echo "core k in, and it is about 130 pcm wide.  The 7152 pcm measured on the"
  echo "4-fuel/4-reflector strip therefore does not propagate to the core: that"
  echo "test over-weighted the reflector by two orders of magnitude."
  echo
  echo "Measured, not argued.  Collapsing all four rings onto the single"
  echo "dataset nearest the core moves k by $(pcm ${K[u4lk_ring_all5]} $REF | tr -d ' ') pcm, so the depth"
  echo "resolution the reflector COMPO provides is worth almost nothing here."
  echo "Putting the cooled ring in the wrong place moves it by $(pcm ${K[u4lk_ring_all8]} $REF | tr -d ' ') and"
  echo "$(pcm ${K[u4lk_ring_rev]} $REF | tr -d ' ') pcm.  WHERE THE WATER IS matters; the spectrum depth does not."
  echo
  echo "What this does NOT bound: a dataset that got graphite ABSORPTION badly"
  echo "wrong would act as a sink rather than a reflector and could fall below"
  echo "the no-reflector row, outside the band above.  The rows here bound"
  echo "datasets built the way ours was, not arbitrary ones."
} > "$OUT"
cat "$OUT"
