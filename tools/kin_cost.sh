#!/usr/bin/env bash
#
# Phase 0 of the transient plan: measure the cost of one KINSOL: step on the
# full DUAL 1 1 core, so A8's timestep and the urgency of the Tier B engine
# rest on a measurement instead of a guess.
#
# Each variant is run twice, at N_LO and N_HI steps, and the per-step cost is
# the DIFFERENCE divided by (N_HI - N_LO).  That cancels the fixed setup --
# geometry, tracking and the FLUD: eigenvalue solve -- exactly, instead of
# estimating it.  Max RSS is reported from the longer run.
#
# Prints a table.  No value in it is typed by hand; rerun to regenerate.
#
set -euo pipefail
. "$(dirname "${BASH_SOURCE[0]}")/env.sh"

GEN="$RBMK_ROOT/decks/Donjon/data/gen_kin_probe.py"
DON="$RBMK_ROOT/5.1/Donjon"
OUT="${1:-$RBMK_ROOT/decks/Donjon/data/kin_cost.txt}"
N_LO=10
N_HI=110

# name | deck | KIN_PERT_MIX | KIN_DSIG | description
VARIANTS=(
  "frozen-step|rbmk_kin_probe|4|0|macrolib frozen, 4-entry KINSOL:"
  "frozen-ramp|rbmk_kin_ramp|4|0|macrolib frozen, 6-entry KINSOL: (MACRO_0/SYST_0 kept)"
  "mild-mix4|rbmk_kin_pert|4|1.3e-3|bottom inner reflector ramp, power -2.4e-4 rel"
  "severe-mix1|rbmk_kin_pert|1|1e-3|fuel absorption ramp, power falls 3200 -> 16 MW"
)

run () {                     # run <deck> <nstep> <pertmix> <dsig> -> "wall rss"
    local deck=$1 n=$2 pm=$3 ds=$4
    KIN_NSTEP="$n" KIN_PERT_MIX="$pm" KIN_DSIG="$ds" python3 "$GEN" >/dev/null
    "$RBMK_ROOT/tools/link_decks.sh" >/dev/null 2>&1
    rm -f "$DON/Linux_aarch64/$deck.don.result"
    ( cd "$DON" && /usr/bin/time -f "%e %M" ./rdonjon "$deck.don" ) 2>&1 \
        | tail -1
}

{
  echo "# KINSOL: cost on the 49x49x32 DUAL 1 1 core (263 329 unknowns/group)"
  echo "# generated by tools/kin_cost.sh -- do not edit"
  echo "# host: $(uname -m) $(nproc) cores; $(date -u +%Y-%m-%dT%H:%MZ)"
  echo "# per-step cost = (wall at $N_HI steps - wall at $N_LO steps) / $((N_HI-N_LO))"
  echo
  printf "%-13s %9s %9s %9s %9s  %s\n" \
         variant "t@$N_LO/s" "t@$N_HI/s" "s/step" "RSS/MB" description
  for v in "${VARIANTS[@]}"; do
      IFS='|' read -r name deck pm ds desc <<<"$v"
      read -r lo _    <<<"$(run "$deck" "$N_LO" "$pm" "$ds")"
      read -r hi rss  <<<"$(run "$deck" "$N_HI" "$pm" "$ds")"
      printf "%-13s %9.2f %9.2f %9.4f %9.1f  %s\n" \
             "$name" "$lo" "$hi" \
             "$(echo "$hi $lo" | awk -v n=$((N_HI-N_LO)) '{printf "%.6f",($1-$2)/n}')" \
             "$(echo "$rss" | awk '{printf "%.1f",$1/1024}')" "$desc"
  done
} | tee "$OUT"

# Leave the tree holding the committed default (severe, the bounding case).
KIN_NSTEP=$N_HI KIN_PERT_MIX=1 KIN_DSIG=1e-3 python3 "$GEN" >/dev/null
"$RBMK_ROOT/tools/link_decks.sh" >/dev/null 2>&1
echo
echo "wrote $OUT"
