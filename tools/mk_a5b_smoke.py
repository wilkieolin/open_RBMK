#!/usr/bin/env python3
"""Derive the A5b smoke deck from the real one, so it cannot drift.

    python tools/mk_a5b_smoke.py        # -> decks/Dragon/data/rbmk_a5b_smoke.x2m

WHY THIS EXISTS.  `rbmk_a5b_smoke.x2m` was generated once, in 2026-09, by a
`/tmp/mksmoke.py` that no longer exists -- and it had already drifted: it still
carries the pre-`EXTR 1` depletion structure, with no `dburn`/`isnode` grids,
so it stopped being a test of the deck it is supposed to smoke-test.  That is
exactly standing rule 6: a copy is not the file everything calls.  This script
makes the smoke deck a derived artefact of `rbmk_a5b_compo.x2m` again.

WHAT IT CHANGES, AND NOTHING ELSE.  The grids shrink and the output file is
renamed.  Geometry, tracking, self-shielding, depletion options, the COMPO:
declaration and the export are the real deck's, byte for byte.

THE GRIDS ARE CHOSEN TO SIT ON THE AXIS EXTREMES, not in the middle: the
point of a smoke test here is the ENDS of each axis, because that is where
A7b found the real deck's axes were too narrow (PROGRESS.md "A7b").  So the
density grid is the new top and the old bottom, and the fuel temperature is
the new floor.
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
SRC = os.path.join(ROOT, "decks", "Dragon", "data", "rbmk_a5b_compo.x2m")
DST = os.path.join(ROOT, "decks", "Dragon", "data", "rbmk_a5b_smoke.x2m")

# (name, new count, new values) -- the whole point is the axis ENDS
GRIDS = {
    "burn":   [0.0, 2000.0],
    "dburn":  [0.0, 500.0, 2000.0],
    "isnode": [1.0, 0.0, 1.0],
    "dca":    None,          # filled from the real deck's first and last
    "tf":     None,          # filled from the real deck's first value
    "tg":     None,          # ditto
}
COUNTS = {"burn": "nbu", "dburn": "ndep", "dca": "ndc", "tf": "ntf", "tg": "ntg"}


def grid_of(src, name):
    m = re.search(rf"CREA '{name}' <<\w+>> =\s*\n?((?:[^;]*?))\s*;", src)
    assert m, f"grid {name} not found"
    return [float(x) for x in m.group(1).split()]


def main():
    src = open(SRC).read()
    real = {g: grid_of(src, g) for g in ("burn", "dburn", "isnode", "dca", "tf", "tg")}
    # the ends of the real axes, which is what needs smoking
    GRIDS["dca"] = [real["dca"][0], real["dca"][-1]]
    GRIDS["tf"] = [real["tf"][0]]
    GRIDS["tg"] = [real["tg"][1] if len(real["tg"]) > 1 else real["tg"][0]]
    out = src

    for name, vals in GRIDS.items():
        pat = re.compile(rf"(CREA '{name}' <<\w+>> =)\s*(?:[^;]*?)\s*;", re.S)
        # ALWAYS emit a decimal point.  UTL: CREA infers the record TYPE from
        # the literals, so "1 0 1" makes isnode an INTEGER record and the
        # REAL  GETVAL 'isnode' ... >>flag<<  then dies with
        # "DRVGRP: NOT ENOUGH CLE-2000 PARAMETERS TO CONTAIN ALL VALUES ASKED
        # TO BE PICKED", which does not mention types at all.
        body = "  ".join(f"{v:.6g}" + ("" if "." in f"{v:.6g}"
                                       or "e" in f"{v:.6g}" else ".0")
                         for v in vals)
        new, n = pat.subn(lambda m: f"{m.group(1)}  {body} ;", out)
        assert n == 1, f"{n} matches rewriting grid {name}"
        out = new
    for name, var in COUNTS.items():
        pat = re.compile(rf"^INTEGER {var} := \d+ ;", re.M)
        new, n = pat.subn(f"INTEGER {var} := {len(GRIDS[name])} ;", out)
        assert n == 1, f"{n} matches rewriting count {var}"
        out = new

    out = out.replace("'./_ACompo'", "'./_ACompoSmoke'")
    assert "_ACompoSmoke" in out
    banner = f"""*----
*  RBMK-1000 -- A5b SMOKE TEST.  GENERATED by tools/mk_a5b_smoke.py from
*  rbmk_a5b_compo.x2m.  DO NOT HAND-EDIT: regenerate it.
*
*  Syntax and plumbing only, on the AXIS ENDS rather than the middle, because
*  that is where A7b found the real axes too narrow:
*      burnup  {" ".join(str(v) for v in GRIDS["burn"])}
*      dca     {" ".join(str(v) for v in GRIDS["dca"])}   (real: {real["dca"][0]} .. {real["dca"][-1]})
*      tf      {" ".join(str(v) for v in GRIDS["tf"])}            (real: {real["tf"][0]} .. {real["tf"][-1]})
*      tg      {" ".join(str(v) for v in GRIDS["tg"])}
*  Writes _ACompoSmoke, never _ACompo.
*----
"""
    open(DST, "w").write(banner + out)
    print(f"wrote {os.path.relpath(DST, ROOT)}")
    print(f"  real axes : dca {real['dca']}")
    print(f"              tf  {real['tf']}")
    print(f"              tg  {real['tg']}")
    print(f"  smoke     : burn {GRIDS['burn']}  dca {GRIDS['dca']}  "
          f"tf {GRIDS['tf']}  tg {GRIDS['tg']}")
    print(f"  branch points: {len(GRIDS['dca']) * len(GRIDS['tf']) * len(GRIDS['tg'])}"
          f" per node x {sum(1 for f in GRIDS['isnode'] if f > 0.5)} nodes")


if __name__ == "__main__":
    sys.exit(main())
