#!/usr/bin/env python3
"""Phase 1b: the radial graphite reflector dataset.

WHY THIS EXISTS.  `gen_rbmk_unit4.py` says it in its own header: the reflector
is a placeholder and the core deck's eigenvalue must not be quoted.  A core
cannot leak correctly without it, so this is the last missing input before the
A6.5 gate can be attempted at all.

THE GEOMETRY, now sourced ([D] p.9, primary, and confirmed three ways):

    "Активная зона имеет форму вертикального цилиндра эквивалентным диаметром
     11,8 и высотой 7 м.  Она окружена боковым отражателем толщиной 1 м и
     торцевыми отражателями толщиной по 0,5 м."

  core 11.8 m across and 7 m high; LATERAL reflector 1 m = 4 columns; END
  reflectors 0.5 m = 2 planes each.  [D] repeats the four rows ("в отверстия
  четырёх рядов периферийных колонн (бокового отражателя) установлены
  графитовые стержни") and gives the stack as 2488 columns of 250 x 250 mm at
  1.65 g/cm3 with 156 reflector cooling channels.  [BEH96] II.B, independently,
  gives 444 pure graphite plus 156 water-cooled = 600, and 2488 - 1888 (our
  channel map) = 600 exactly.

  So the radial reflector is FOUR rings and TWO materials: three rings of
  graphite columns with graphite rods in the bore, and an outermost ring
  carrying the 156 cooling channels.

THE MODEL.  An 8-cell strip, 4 fuel then 4 reflector: reflective on the core
side (an infinite core beyond), vacuum outside the stack, reflective across
the strip.  Four fuel cells because the migration length is of order a metre
-- four pitches -- so the fuel-side spectrum needs that much room to relax to
asymptotic before the boundary, and A6.4 showed exactly how far a perturbation
reaches.  `EDI: MERG CELL` then gives eight zones and the reflector constants
come out resolved BY DEPTH, which is what a 1 m reflector needs: the spectrum
at ring 1 is not the spectrum at ring 4.

WHAT IS NOT SOURCED, and is therefore carried as a declared band rather than
quietly chosen (the treatment B4C density already gets):

  * the cooling channel's dimensions.  [D] describes it as a Field tube of
    corrosion-resistant steel -- water down the centre, up the annulus -- and
    gives no sizes outside the figure.  Parameterised by tube outer radius.
  * the reflector graphite temperature.  The reflector is cooler than the
    core's 750 K, but no source in hand gives a number.
"""
import os
import sys

import cps_common as cc

ROOT, DATA, PROC, DON = cc.ROOT, cc.DATA, cc.PROC, cc.DON

# DRAGON mixtures.  1-9 are RbmkLib's fuel cell, 10-15 the CPS cell
# (RbmkCpsLib), so the reflector starts at 16 and the three sets compose.
MIXR = {"grefl": 16, "steel": 17, "wrefl": 18}

RHO_GRAPH = 1.65            # g/cm3, [D]: the stack's graphite density
T_GREFL = 600.0             # K -- OPEN INPUT, see the header
R_BORE = 5.70               # cm, the 114 mm bore, as the fuel cell ([D] p.11)
R_BLOCK = 11.00             # cm, RbmkGeo's outer graphite ring
R_TUBE_O = 3.80             # cm -- OPEN INPUT: Field tube outer radius
T_WALL = 0.40               # cm -- OPEN INPUT: its wall
T_WREFL = cc.T_CPS          # K, the reflector cooling water; same circuit
                            # temperature as the CPS water, 50 C [D] p.12

NFUEL_CELLS = 4
NG_CELLS = 3                # pure graphite rings
NW_CELLS = 1                # the outermost, water-cooled ring


def steel(rho=7.90):
    """08Kh18N10T, the Soviet austenitic stainless of the reactor internals.

    Nominal composition in weight per cent: C 0.08, Si 0.8, Mn 2.0, Cr 18,
    Ni 10, Ti 0.7, iron the balance.  Sums to 0.08696 atom/b-cm at 7.90 g/cm3,
    which is the usual figure for this class of steel -- the check that the
    weight-to-atom conversion has not gone wrong.
    """
    wt = {"C": 0.0008, "Si": 0.008, "Mn": 0.02, "Cr": 0.18, "Ni": 0.10,
          "Ti": 0.007}
    wt["Fe"] = 1.0 - sum(wt.values())
    return cc._weight_to_atoms(rho, wt)


def materials(t_grefl=T_GREFL, rho_graph=RHO_GRAPH, t_wrefl=T_WREFL):
    return {
        MIXR["grefl"]: ("reflector graphite", t_grefl, cc.graphite(rho_graph)),
        MIXR["steel"]: ("08Kh18N10T Field tube", t_wrefl, steel()),
        MIXR["wrefl"]: ("reflector cooling water", t_wrefl, cc.water()),
    }


def refl_lib():
    """RbmkReflLib.c2m: adds MIX 16-18 to a LIBRARY that holds the fuel cell."""
    out = ["*DECK RbmkReflLib", "*----",
           "*  Radial-reflector mixtures, added to a LIBRARY that already holds",
           "*  the fuel cell (RbmkLib, optionally with burned fuel).",
           "*  GENERATED by openmc/refl.py -- edit that, not this file.",
           "*",
           "*  Called as:  LIBRARY := RbmkReflLib LIBRARY :: <<tgr>> <<rhogr>> ;",
           "*    tgr    reflector graphite temperature K (OPEN INPUT: the",
           "*           reflector runs cooler than the core's 750 K and no",
           "*           source in hand gives a number -- run it as a band)",
           "*    rhogr  reflector graphite density g/cm3 ([D]: 1.65)",
           "*",
           "*  The steel is NOT self-shielded: its Fe, Cr and Ni resonances sit",
           "*  at infinite dilution, as B10/B11 do in RbmkCpsLib.  It is a thin",
           "*  tube in the outermost of four rings, where the flux is already",
           "*  down by orders of magnitude, but that is an argument and not a",
           "*  measurement -- it is on the list to check, not established.",
           "*----",
           "PARAMETER LIBRARY ::", "   EDIT 0", "      ::: LINKED_LIST LIBRARY ;", ";",
           "MODULE LIB: END: ;", "REAL tgr rhogr ;", ":: >>tgr<< >>rhogr<< ;"]
    nc = cc.graphite(1.0)["C12"]
    out.append(f"REAL nC12R := {nc:.6E} rhogr * ;")
    out += ["", "LIBRARY := LIB: LIBRARY ::", "  EDIT 0",
            f"  NMIX {max(MIXR.values())}", "  MIXS LIB: DRAGON FIL: DLIB_99"]
    for mix, (name, t, comp) in materials().items():
        tt = "<<tgr>>" if mix == MIXR["grefl"] else f"{t:.2f}"
        out += ["", f"* MIX {mix}: {name}", f"  MIX     {mix}  {tt}"]
        for n, d in comp.items():
            if mix == MIXR["grefl"]:
                out.append(f"     {'C12_GR':<7s} = {'C12_GR':<7s} <<nC12R>>")
                continue
            dn = "H1_H2O" if (n == "H1" and mix == MIXR["wrefl"]) else n
            out.append(f"     {dn:<7s} = {dn:<7s} {d:.5E}")
    out += ["  ;", "", "END: ;", "QUIT ."]
    return "\n".join(out) + "\n"


def _graphite_cell():
    """A reflector column: the 114 mm bore plugged with a graphite rod ([D]).

    Modelled as solid graphite.  The rod does not fill the bore exactly and
    there is a gas annulus, but no source in hand gives the rod diameter, and
    a gas gap of a few millimetres in a metre of graphite is not where this
    model's error is.  Split into three radial zones so the tracking resolves
    the flux gradient through the ring, not because the material changes.
    """
    g = MIXR["grefl"]
    return f"""  ::: G := GEO: CARCEL 2
    MESHX 0.0 25.0 MESHY 0.0 25.0
    RADIUS 0.0000 {R_BORE:.4f} {R_BLOCK:.4f}
    MIX {g} {g} {g}
    ;"""


def _cooled_cell(r_tube_o=R_TUBE_O, t_wall=T_WALL):
    """The outermost ring: a steel Field tube carrying water, in the bore."""
    ri = r_tube_o - t_wall
    w, s, g = MIXR["wrefl"], MIXR["steel"], MIXR["grefl"]
    return f"""  ::: W := GEO: CARCEL 4
    MESHX 0.0 25.0 MESHY 0.0 25.0
    RADIUS 0.0000 {ri:.4f} {r_tube_o:.4f} {R_BORE:.4f} {R_BLOCK:.4f}
    MIX {w} {s} 3 {g} {g}
    ;"""


def refl_geo():
    """RbmkScRefl.c2m: the 4-fuel + 4-reflector strip, coarse and refined."""
    cells = " ".join(["F"] * NFUEL_CELLS + ["G"] * NG_CELLS + ["W"] * NW_CELLS)
    n = NFUEL_CELLS + NG_CELLS + NW_CELLS
    mesh = " ".join(f"{25.0*i:.1f}" for i in range(n + 1))
    ks = [1, 2, 3, 4, 6]

    def geo(split):
        fsplit = "    SPLITR <<k4>> <<k1>> <<k1>> <<k2>> <<k6>>\n" if split else ""
        csplit = "SPLITR <<k1>> <<k1>> <<k1>> " if split else ""
        rsplit = "SPLITR <<k1>> <<k3>> <<k1>> <<k1>> " if split else ""
        body = cc.FUEL_CELL.format(fsplit=fsplit, csplit=csplit, rsplit=rsplit)
        body += "\n" + _graphite_cell() + "\n" + _cooled_cell()
        return f"""GEO: :: CAR2D {n} 1
  EDIT 0
  X- REFL X+ VOID  Y- REFL Y+ REFL
  MESHX {mesh}  MESHY 0.0 25.0
  CELL {cells}
{body}
  ;"""
    kdecl = "\n".join(f"INTEGER k{s} := {s} k * ;" for s in ks)
    return f"""*DECK RbmkScRefl
*----
*  Core/reflector strip: {NFUEL_CELLS} fuel cells, {NG_CELLS} graphite
*  reflector columns, {NW_CELLS} water-cooled column.  [D] p.9: the lateral
*  reflector is 1 m = 4 columns; [BEH96] II.B and [D] agree the outermost
*  carries the 156 cooling channels.
*  GENERATED by openmc/refl.py -- edit that, not this file.
*
*  X- REFL  an infinite core beyond the fuel side
*  X+ VOID  outside the graphite stack
*  Y+/Y- REFL  the strip repeats along the reflector face
*
*  The fuel cell is RbmkGeo.c2m's, verbatim, so this and the CPS supercells
*  cannot drift apart.
*----
PARAMETER GEOSS GEOFL ::
   EDIT 0
      ::: LINKED_LIST GEOSS GEOFL ;
;
MODULE GEO: END: ;
INTEGER k ;
:: >>k<< ;
{kdecl}

GEOSS := {geo(False)}

GEOFL := {geo(True)}

END: ;
QUIT .
"""


# ---------------------------------------------------------------------------
# The DRAGON deck
# ---------------------------------------------------------------------------

REFL_BUS = [0.0, 10900.0]       # fresh, and the Unit 4 core average
REFL_DCAS = [0.72, 0.02]        # nominal and drained: measures the sensitivity
NZONE = NFUEL_CELLS + NG_CELLS + NW_CELLS


def refl_deck(bus=None, dcas=None, t_grefl=T_GREFL):
    """rbmk_refl.x2m -- the radial reflector dataset.

    Four states, not one.  The reflector's own constants depend on the
    spectrum arriving from the core, which depends on the adjacent fuel's
    burnup and coolant density, and nobody has measured how much.  Two burnups
    and two densities make that a result rather than an assumption.

    `FLU: TYPE K` with no B1: the slab leaks through its X+ VOID face, so the
    leakage is explicit in the geometry and a buckling model on top of it would
    be counting the same thing twice.  (The CPS supercells use B1 BUCK 0.0
    because they are fully reflected and have no leakage at all; there the
    zero-buckling B1 is only a flag to make COMPO: keep GOLVER's DIFF.  Check
    DIFF survives here -- if it does not, that is what the flag was for.)
    """
    bus = bus or REFL_BUS
    dcas = dcas or REFL_DCAS
    nodes = cc.BU_NODES[:cc.BU_NODES.index(max(bus)) + 1]
    L = [f"""*----
*  A6.5 / Phase 1b -- RADIAL REFLECTOR DATASET.
*  GENERATED by openmc/refl.py.  Edit the generator, not this file.
*
*  {NFUEL_CELLS} fuel cells then {NG_CELLS} graphite reflector columns and
*  {NW_CELLS} water-cooled column: the 1 m lateral reflector of [D] p.9,
*  four columns, with [BEH96]'s 156 cooled channels in the outermost ring.
*  Reflective on the core side, VACUUM outside the stack.
*
*  Output: REFLTAB <bu> <dca> <k>;  _RCompo holds {NZONE} zones, resolved by
*  depth, because the spectrum at ring 1 is not the spectrum at ring 4.
*----
LINKED_LIST LIBRARY LIBSS GEOSS GEOFL TRKSS TRK SYS FLUX BURNUP
            SCSS SCFL SCTRKSS SCTRK EDIOBJ GEOMAC MTRACK COMPO ;
SEQ_BINARY  FTRKSS FTRK SCFTRKSS SCFTRK ;
SEQ_ASCII   _RCompo :: FILE './_RCompo' ;
MODULE      LIB: GEO: NXT: USS: ASM: FLU: EVO: EDI: SPH: TRIVAT: COMPO: UTL:
            GREP: DELETE: END: ;
PROCEDURE   RbmkLib RbmkGeo RbmkReflLib RbmkScRefl ;
REAL tgnom := 750.0 ;
REAL tgrefl := {t_grefl} ;
REAL rhogr := {RHO_GRAPH} ;
REAL tcool := 573.0 ;
REAL fpwr  := 16.7 ;
REAL kinf tbeg tend ;

*--- deplete the ordinary fuel cell, exactly as rbmk_a5b_compo does
GEOSS GEOFL := RbmkGeo ;
TRKSS FTRKSS := NXT: GEOSS :: EDIT 0 TITLE 'CELL-SS' ALLG BATCH 100 TISO 8 15.0 ;
TRK FTRK := NXT: GEOFL :: EDIT 0 TITLE 'CELL-FL' ALLG BATCH 100 TISO 15 30.0 ;
LIBRARY := RbmkLib :: 0.72 900.0 <<tgnom>> <<tcool>> ;
LIBSS := USS: LIBRARY TRKSS FTRKSS :: EDIT 0 PASS 2 MAXST 300 ;
SYS := ASM: LIBSS TRK FTRK :: EDIT 0 ;
FLUX := FLU: LIBSS TRK SYS :: TYPE K EXTE 1.0E-6 ;
EVALUATE tend := 0.0 ;
BURNUP LIBSS := EVO: LIBSS FLUX TRK :: EDIT 0 SAVE <<tend>> DAY POWR <<fpwr>> ;"""]
    for b in nodes[1:]:
        L.append(f"""EVALUATE tbeg tend := tend {b} fpwr / ;
BURNUP LIBSS := EVO: BURNUP LIBSS FLUX TRK ::
  EDIT 0 EXTR 1 DEPL <<tbeg>> <<tend>> DAY POWR <<fpwr>> ;
SYS := DELETE: SYS ;
SYS := ASM: LIBSS TRK FTRK :: EDIT 0 ;
FLUX := FLU: FLUX LIBSS TRK SYS :: TYPE K EXTE 1.0E-6 ;
BURNUP LIBSS := EVO: BURNUP LIBSS FLUX TRK :: EDIT 0 SAVE <<tend>> DAY POWR <<fpwr>> ;""")
    mesh = " ".join(f"{25.0*i:.1f}" for i in range(NZONE + 1))
    grid = " ".join(str(m) for m in range(1, NZONE + 1))
    L.append(f"""LIBRARY LIBSS SYS FLUX := DELETE: LIBRARY LIBSS SYS FLUX ;

SCSS SCFL := RbmkScRefl :: 1 ;
SCTRKSS SCFTRKSS := NXT: SCSS :: EDIT 0 TITLE 'RF-SS' ALLG BATCH 100 TISO 8 15.0 ;
SCTRK SCFTRK := NXT: SCFL :: EDIT 0 TITLE 'RF-FL' ALLG BATCH 100 TISO 15 30.0 ;

*  Macro-geometry for SPH: one homogeneous 25 cm node per column, as the core
*  has, on the SAME DUAL 1 1 the core must use (A6.4: MCFD cannot carry a
*  converged SPH equivalence and loses a third of the absorber worth).
GEOMAC := GEO: :: CAR2D {NZONE} 1
  X- REFL X+ VOID  Y- REFL Y+ REFL
  MESHX {mesh}  MESHY 0.0 25.0
  MIX {grid} ;
MTRACK := TRIVAT: GEOMAC :: EDIT 0 MAXR 40 DUAL 1 1 ;

COMPO := COMPO: ::
  EDIT 1
  STEP UP 'EDIREFL'
  MAXCAL 5
  COMM 'RBMK radial reflector, {NFUEL_CELLS}F+{NG_CELLS}G+{NW_CELLS}W strip' ENDC
  PARA 'burnup' IRRA
  PARA 'DCA' VALU REAL
  INIT
  ;""")
    for bu in bus:
        istep = cc.BU_NODES.index(bu) + 1
        for dca in dcas:
            burn = "" if bu == 0.0 else \
                f"LIBRARY := LIB: LIBRARY BURNUP :: EDIT 0 BURN {istep} MIX 6 MIX 7 ;\n"
            L.append(f"""
LIBRARY := RbmkLib :: {dca} 900.0 <<tgnom>> <<tcool>> ;
{burn}LIBRARY := RbmkReflLib LIBRARY :: <<tgrefl>> <<rhogr>> ;
LIBSS := USS: LIBRARY SCTRKSS SCFTRKSS :: EDIT 0 PASS 2 MAXST 300 ;
SYS := ASM: LIBSS SCTRK SCFTRK :: EDIT 0 ;
FLUX := FLU: LIBSS SCTRK SYS :: TYPE K EXTE 1.0E-6 ;
GREP: FLUX :: GETVAL 'K-EFFECTIVE' 1 >>kinf<< ;
ECHO "REFLTAB" {bu} {dca} kinf ;
EDIOBJ := EDI: LIBSS SCTRK FLUX SCFL SYS GEOMAC ::
  EDIT 0 MERG CELL NXT COND 0.625 GOLVER MGEO GEOMAC SAVE ON EDIREFL ;
*  ASYM 1: normalise on the fuel cell farthest from the reflector, so the
*  reflector zones carry the whole correction and the core's own fuel data
*  (which is uncorrected) stays consistent with zone 1.
EDIOBJ := SPH: EDIOBJ MTRACK :: EDIT 1 ASYM 1 ITER 1.0E-6 200 ;
EVALUATE tend := {bu} fpwr / ;
COMPO := COMPO: COMPO EDIOBJ BURNUP LIBRARY ::
  EDIT 0 STEP UP 'EDIREFL' 'DCA' {dca} SET <<tend>> DAY ;
LIBRARY LIBSS SYS FLUX EDIOBJ := DELETE: LIBRARY LIBSS SYS FLUX EDIOBJ ;""")
    L.append("""
_RCompo := COMPO ;
UTL: COMPO :: DIR ;
ECHO "rbmk_refl completed" ;
END: ;
QUIT .
""")
    text = "\n".join(L)
    over = [i + 1 for i, l in enumerate(text.splitlines()) if len(l) > 120]
    if over:
        sys.exit(f"refl: lines over 120 columns: {over[:5]}")
    return text


SAVE_HOOK = """#!/bin/sh
cp _RCompo "$1"/../Dragon/compo/ 2>/dev/null
"""


def write():
    open(os.path.join(PROC, "RbmkReflLib.c2m"), "w").write(refl_lib())
    open(os.path.join(PROC, "RbmkScRefl.c2m"), "w").write(refl_geo())
    p = os.path.join(DATA, "rbmk_refl.x2m")
    open(p, "w").write(refl_deck())
    a = os.path.join(DATA, "rbmk_refl.access")
    if os.path.lexists(a):
        os.remove(a)
    os.symlink("../../common/rbmk.access", a)
    sv = os.path.join(DATA, "rbmk_refl.save")
    open(sv, "w").write(SAVE_HOOK)
    os.chmod(sv, 0o755)
    for f in ("rbmk_proc/RbmkReflLib.c2m", "rbmk_proc/RbmkScRefl.c2m"):
        q = os.path.join(DATA, f)
        over = [i + 1 for i, l in enumerate(open(q).read().splitlines())
                if len(l) > 120]
        if over:
            sys.exit(f"refl: {f} over 120 columns at {over[:3]}")
    print("wrote", os.path.relpath(p, ROOT))
    print(f"  states: {len(REFL_BUS)} burnups x {len(REFL_DCAS)} densities")
    print(f"  zones:  {NZONE}  ({NFUEL_CELLS} fuel, {NG_CELLS} graphite, "
          f"{NW_CELLS} cooled)")


if __name__ == "__main__":
    write()
