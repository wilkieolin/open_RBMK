#!/usr/bin/env python3
"""Superposition test: does a fuel cell's environment perturbation add up?

WHY THIS DECIDES THE SCOPE OF A6.4.  A6.4b is dead (PROGRESS.md, 2026-09-30):
no rod-only SPH factor closes the gate, because the error lives in the eight
fuel cells around the rod, which differ from infinite-lattice fuel by a few
per cent.  The surviving fix is to make the fuel cross sections depend on the
local CPS environment.  Whether that is days of work or weeks turns on one
question:

    is the perturbation ADDITIVE in the number of CPS neighbours?

If yes, environment is a CONTINUOUS axis -- something like the CPS count in
the eight-ring -- which interpolates, handles rods moving mid-transient, and
needs only a handful of supercell calculations.  If no, it has to be discrete
classes enumerated by configuration, and the cost goes up an order of
magnitude.

THE DESIGN.  One 5 x 5 supercell with TWO CPS channels, at (1,1) and (3,3) in
a 0-based periodic 5 x 5.  That single geometry contains fuel cells with 0, 1
and 2 CPS channels in their eight-ring, so the comparison is internal: same
library, same state, same tracking, same fuel.  Nothing is differenced across
runs that were set up separately.

    (0,0)  1 CPS, diagonal          (1,2)  1 CPS, orthogonal
    (2,2)  2 CPS, both diagonal     (1,3)  0 CPS in the ring
    CPS fraction 2/25 = 8 %, against Unit 4's 227/1888 = 12 %

The infinite-lattice reference is the ordinary RbmkGeo cell, computed in the
SAME deck at the same state, so the perturbation is a clean ratio.

WHY THE CPS CHANNELS SIT ON THE DIAGONAL.  EDI: MERG CELL numbers its merged
regions cell by cell, and the 3 x 3 deck dodges the row-major/column-major
question only because its single centre cell is region 5 either way.  A 5 x 5
cannot dodge it -- except that {(1,1), (3,3)} is symmetric under transpose, so
every cell (i,j) has the same CPS environment as (j,i).  The classification is
therefore invariant to the raster order, and a wrong guess about it cannot
corrupt the result.  That is the reason for this placement, not aesthetics.

Fresh fuel only.  A6.4 item 3 showed the whole effect is present at zero
burnup, so depletion would add an hour and nothing else.
"""
import math
import os
import re
import subprocess
import sys

import cps_common as cc

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = cc.ROOT
DATA = cc.DATA
PROC = cc.PROC
DON = cc.DON

N = 5
CPS_AT = [(1, 1), (3, 3)]          # 0-based (row, col)
STYPE = "ABS"                      # strongest perturbation: best signal


def ring_counts():
    """CPS channels in each fuel cell's eight-ring, under 5 x 5 periodicity."""
    cps = set(CPS_AT)
    out = {}
    for i in range(N):
        for j in range(N):
            if (i, j) in cps:
                continue
            e = sum(1 for d in ((1, 0), (-1, 0), (0, 1), (0, -1))
                    if ((i + d[0]) % N, (j + d[1]) % N) in cps)
            c = sum(1 for d in ((1, 1), (1, -1), (-1, 1), (-1, -1))
                    if ((i + d[0]) % N, (j + d[1]) % N) in cps)
            out[(i, j)] = (e, c)
    return out


def geo_proc():
    """RbmkSc5<type>.c2m -- the 5 x 5, built from cps_common's own cell blocks."""
    cells = [["F"] * N for _ in range(N)]
    for i, j in CPS_AT:
        cells[i][j] = "C"
    rows = "\n       ".join(" ".join(r) for r in cells)
    ks = sorted({s for _, _, s in cc.SECTIONS.get(STYPE, [])} | {1, 2, 3, 4, 6})

    def geo(split):
        fsplit = "    SPLITR <<k4>> <<k1>> <<k1>> <<k2>> <<k6>>\n" if split else ""
        csplit = "SPLITR <<k1>> <<k1>> <<k1>> " if split else ""
        rsplit = "SPLITR <<k1>> <<k3>> <<k1>> <<k1>> " if split else ""
        body = cc.FUEL_CELL.format(fsplit=fsplit, csplit=csplit, rsplit=rsplit)
        body += "\n" + cc._cps_cell(STYPE, split)
        return f"""GEO: :: CAR2D {N} {N}
  EDIT 0
  X- REFL X+ REFL Y- REFL Y+ REFL
  CELL {rows}
{body}
  ;"""
    kdecl = "\n".join(f"INTEGER k{s} := {s} k * ;" for s in ks)
    cnt = ring_counts()
    note = "\n".join(
        f"*    cell {i},{j} (mix {i*N+j+1:2d}): {e} orthogonal, {c} diagonal"
        for (i, j), (e, c) in sorted(cnt.items()))
    return f"""*DECK RbmkSc5{STYPE}
*----
*  {N} x {N} CPS supercell, centre type {STYPE}, CPS at {CPS_AT}.
*  GENERATED by openmc/sup5.py -- edit that, not this file.
*  The fuel cell and the CPS cell are cps_common's, byte for byte the ones the
*  3 x 3 supercell uses, so the two geometries differ only in layout.
*
*  CPS channels in each fuel cell's eight-ring (periodic):
{note}
*----
PARAMETER GEOSS GEOFL ::
   EDIT 0
      ::: LINKED_LIST GEOSS GEOFL ;
;
MODULE GEO: END: ;
INTEGER k ;
:: >>k<< ;
{kdecl}

GEOSS := {geo(False)}

GEOFL := {geo(True)}

END: ;
QUIT .
"""


def dragon_deck():
    """One state, no depletion.  EDI: MERG CELL -> 25 cells, stored in a COMPO.

    NO SPH.  The question here is what the raw homogenisation does, and an SPH
    normalisation would smear the answer across the cells -- which is exactly
    the trap noted against reading the 3 x 3's per-cell numbers as physics
    (ASYM 1 pins the corner, so its factor absorbs none of the difference and
    its neighbours' factors absorb some of theirs).
    """
    grid = "\n".join("  " + " ".join(f"{i*N+j+1:3d}" for j in range(N))
                     for i in range(N))
    return f"""*----
*  A6.4 SUPERPOSITION TEST -- {N} x {N} supercell, {len(CPS_AT)} CPS channels.
*  GENERATED by openmc/sup5.py.  Edit the generator, not this file.
*
*  Fresh fuel, dca 0.72, TF 900 K: one state.  A6.4 item 3 established the
*  whole neighbour effect is present at zero burnup, so depletion would cost
*  an hour and change nothing.
*
*  Also computes the ORDINARY single cell in the same deck, at the same state
*  with the same library and tracking, as the infinite-lattice reference.
*
*  Output: SUP5 <mix> <k-inf>, and the per-cell constants via the COMPO.
*----
LINKED_LIST LIBRARY LIBSS GEOSS GEOFL TRKSS TRK SYS FLUX EDIOBJ
            CGEOSS CGEOFL CTRKSS CTRK CSYS CFLUX GEOMAC COMPO ;
SEQ_BINARY  FTRKSS FTRK CFTRKSS CFTRK ;
SEQ_ASCII   _CCompoS5 :: FILE './_CCompoS5' ;
*  The L_EDIT is persisted too.  The physics above costs ~18 minutes and the
*  book-keeping below cost a whole run once already (COMPO.f:477 wants a
*  depletion object for SET .. DAY).  With the edit on disk, any further
*  iteration on the COMPO or the read-out is seconds.
SEQ_ASCII   _EdiS5    :: FILE './_EdiS5' ;
MODULE      LIB: GEO: NXT: USS: ASM: FLU: EDI: COMPO: GREP: DELETE: END: ;
PROCEDURE   RbmkLib RbmkGeo RbmkCpsLib RbmkSc5{STYPE} ;
REAL tgnom := 750.0 ;
REAL tcool := 573.0 ;
REAL kinf kcell ;

*--- the infinite-lattice single cell.  Its k-inf is a consistency check that
*    this deck's library and tracking reproduce the basis the fuel COMPO was
*    built on; the reference CROSS SECTIONS come from _ACompo in the DONJON
*    step, which is the same cell and what the core actually uses.
CGEOSS CGEOFL := RbmkGeo ;
CTRKSS CFTRKSS := NXT: CGEOSS :: EDIT 0 TITLE 'C-SS' ALLG BATCH 100 TISO 8 15.0 ;
CTRK CFTRK := NXT: CGEOFL :: EDIT 0 TITLE 'C-FL' ALLG BATCH 100 TISO 15 30.0 ;
LIBRARY := RbmkLib :: 0.72 900.0 <<tgnom>> <<tcool>> ;
LIBSS := USS: LIBRARY CTRKSS CFTRKSS :: EDIT 0 PASS 2 MAXST 300 ;
CSYS := ASM: LIBSS CTRK CFTRK :: EDIT 0 ;
CFLUX := FLU: LIBSS CTRK CSYS :: TYPE K B1 SIGS BUCK 0.0 EXTE 1.0E-6 ;
GREP: CFLUX :: GETVAL 'K-INFINITY' 1 >>kcell<< ;
ECHO "SUP5CELL kinf=" kcell ;
LIBRARY LIBSS CSYS CFLUX := DELETE: LIBRARY LIBSS CSYS CFLUX ;

*--- the {N} x {N} supercell
GEOSS GEOFL := RbmkSc5{STYPE} :: 1 ;
TRKSS FTRKSS := NXT: GEOSS :: EDIT 0 TITLE 'S5-SS' ALLG BATCH 100 TISO 8 15.0 ;
TRK FTRK := NXT: GEOFL :: EDIT 0 TITLE 'S5-FL' ALLG BATCH 100 TISO 15 30.0 ;
LIBRARY := RbmkLib :: 0.72 900.0 <<tgnom>> <<tcool>> ;
LIBRARY := RbmkCpsLib LIBRARY ::
  {cc.B4C_DENSITY['nom']} {cc.DSP_DENSITY['nom']} {cc.T_DSP} {cc.T_CPS} ;
LIBSS := USS: LIBRARY TRKSS FTRKSS :: EDIT 0 PASS 2 MAXST 300 ;
SYS := ASM: LIBSS TRK FTRK :: EDIT 0 ;
FLUX := FLU: LIBSS TRK SYS :: TYPE K B1 SIGS BUCK 0.0 EXTE 1.0E-6 ;
GREP: FLUX :: GETVAL 'K-INFINITY' 1 >>kinf<< ;
ECHO "SUP5 kinf=" kinf ;

GEOMAC := GEO: :: CAR2D {N} {N}
  X- REFL X+ REFL Y- REFL Y+ REFL
  MESHX 0.0 25.0 50.0 75.0 100.0 125.0
  MESHY 0.0 25.0 50.0 75.0 100.0 125.0
  MIX
{grid}
  ;
*  EDIT 3 so the homogenised constants are printed as well as stored -- a
*  second, independent route to the same numbers if the COMPO path misbehaves.
EDIOBJ := EDI: LIBSS TRK FLUX GEOFL SYS GEOMAC ::
  EDIT 3 MERG CELL NXT COND 0.625 GOLVER MGEO GEOMAC SAVE ON EDIS5 ;
_EdiS5 := EDIOBJ ;

*  One state, so one axis and NO burnup: 'burnup' IRRA is filled from a
*  depletion object, and SET <t> DAY demands one (COMPO.f:477).  There is no
*  depletion in this deck and asking for either aborts after the 18 minutes
*  of physics have already been spent.
COMPO := COMPO: ::
  EDIT 1 STEP UP 'EDIS5' MAXCAL 3
  COMM 'A6.4 superposition test, {N}x{N}, CPS at {CPS_AT}' ENDC
  PARA 'DCA' VALU REAL
  INIT ;
COMPO := COMPO: COMPO EDIOBJ LIBRARY ::
  EDIT 0 STEP UP 'EDIS5' 'DCA' 0.72 ;
_CCompoS5 := COMPO ;

ECHO "rbmk_cps_sup5 completed" ;
END: ;
QUIT .
"""


def write():
    open(os.path.join(PROC, f"RbmkSc5{STYPE}.c2m"), "w").write(geo_proc())
    p = os.path.join(DATA, "rbmk_cps_sup5.x2m")
    open(p, "w").write(dragon_deck())
    a = os.path.join(DATA, "rbmk_cps_sup5.access")
    if os.path.lexists(a):
        os.remove(a)
    os.symlink("../../common/rbmk.access", a)
    sv = os.path.join(DATA, "rbmk_cps_sup5.save")
    open(sv, "w").write("#!/bin/sh\nfor f in _CCompoS5 _EdiS5; do\n"
                    "  cp $f \"$1\"/../Dragon/compo/ 2>/dev/null\ndone\n")
    os.chmod(sv, 0o755)
    for f in (os.path.join(PROC, f"RbmkSc5{STYPE}.c2m"), p):
        over = [i + 1 for i, l in enumerate(open(f).read().splitlines()) if len(l) > 120]
        if over:
            sys.exit(f"sup5: {f} lines over 120 columns: {over[:5]}")
    print("wrote", os.path.relpath(p, ROOT))
    print("ring counts (orthogonal, diagonal):")
    for (i, j), v in sorted(ring_counts().items()):
        print(f"   cell {i},{j}  mix {i*N+j+1:2d}  {v}")




# ---------------------------------------------------------------------------
# The read-out: per-cell constants from the 5 x 5, against infinite lattice
# ---------------------------------------------------------------------------

NM = N * N


def donjon_deck():
    """Read the 5 x 5 COMPO's 25 cells and the fuel COMPO's single cell, and
    print both through OUT: INTG MIX so the comparison runs through one path.

    The 5 x 5 geometry here is only a carrier for OUT:'s macro-zones -- the
    cross sections are what is being read, not a flux solution worth trusting.
    Mixture 26 is the infinite-lattice reference, placed in a cell of its own.
    """
    grid = "\n".join("  " + " ".join(f"{i*N+j+1:3d}" for j in range(N))
                     for i in range(N))
    ref = "\n".join(
        f"  MIX {m} FROM 1 SET 'burnup' 0.0 SET 'DCA' 0.72 SET 'TF' 900.0"
        f" SET 'TG' 750.0 ENDMIX" for m in range(1, NM + 1))
    s5 = "\n".join(
        f"  MIX {m} FROM {m} SET 'DCA' 0.72 ENDMIX"
        for m in range(1, NM + 1))
    mesh = " ".join(f"{25.0*i:.1f}" for i in range(N + 1))
    return f"""*----
*  A6.4 SUPERPOSITION READ-OUT.  GENERATED by openmc/sup5.py.
*  Prints the {NM} cell constants of the {N}x{N} supercell and, separately, the
*  infinite-lattice fuel cell from the fuel COMPO, through the same OUT: path.
*----
LINKED_LIST SCpo FCpo MS5 MREF OUTM GEOM TRACK SYSTEM FLUX ;
SEQ_ASCII   _CCompoS5 :: FILE './_CCompoS5' ;
*  The L_EDIT is persisted too.  The physics above costs ~18 minutes and the
*  book-keeping below cost a whole run once already (COMPO.f:477 wants a
*  depletion object for SET .. DAY).  With the edit on disk, any further
*  iteration on the COMPO or the read-out is seconds.
SEQ_ASCII   _EdiS5    :: FILE './_EdiS5' ;
SEQ_ASCII   _ACompo   :: FILE './_ACompo' ;
MODULE      NCR: GEO: TRIVAT: TRIVAA: FLUD: OUT: GREP: DELETE: END: ;
REAL kk ;
SCpo := _CCompoS5 ;
FCpo := _ACompo ;

GEOM := GEO: :: CAR2D {N} {N}
  X- REFL X+ REFL Y- REFL Y+ REFL
  MESHX {mesh} MESHY {mesh}
  MIX
{grid}
  ;
TRACK := TRIVAT: GEOM :: EDIT 0 MAXR 40 DUAL 1 1 ;
MS5 := NCR: SCpo :: EDIT 0 MACRO LINEAR NMIX {NM}
  COMPO SCpo 'EDIS5'
{s5}  ;
SYSTEM := TRIVAA: MS5 TRACK :: EDIT 0 ;
FLUX := FLUD: SYSTEM TRACK :: EDIT 0 EXTE 1.0E-7 ;
GREP: FLUX :: GETVAL 'K-EFFECTIVE' 1 >>kk<< ;
ECHO "SUP5OUT S5" kk ;
OUTM := OUT: FLUX TRACK MS5 GEOM :: EDIT 2 INTG MIX ;
OUTM SYSTEM FLUX := DELETE: OUTM SYSTEM FLUX ;

*--- the infinite-lattice reference.  SAME geometry, SAME tracking, same OUT:
*    path -- only the data differs: every one of the 25 mixtures is the fuel
*    COMPO's single infinite-lattice cell.  Two reasons for doing it this way
*    rather than on a 1x1 geometry.  First, TRIVAT: DUAL 1 1 on a 1x1 mesh is
*    degenerate and leaves no 'MUX' block for TRIVAA:.  Second, 25 mixtures
*    that are identical by construction must read back identical, so the
*    spread across them measures the read-out path itself.
MREF := NCR: FCpo :: EDIT 0 MACRO LINEAR NMIX {NM}
  COMPO FCpo 'EDIRBMK'
{ref}  ;
SYSTEM := TRIVAA: MREF TRACK :: EDIT 0 ;
FLUX := FLUD: SYSTEM TRACK :: EDIT 0 EXTE 1.0E-7 ;
GREP: FLUX :: GETVAL 'K-EFFECTIVE' 1 >>kk<< ;
ECHO "SUP5OUT REF" kk ;
OUTM := OUT: FLUX TRACK MREF GEOM :: EDIT 2 INTG MIX ;

ECHO "rbmk_cps_sup5_out completed" ;
END: ;
QUIT .
"""


DON_ACCESS = """#!/bin/sh
src="$1"/../Dragon/compo
cp "$src"/_CCompoS5 . || exit 1
cp "$src"/_ACompo . || exit 1
"""


def analyse():
    import a64b
    name = "rbmk_cps_sup5_out"
    p = os.path.join(DON, name + ".don")
    open(p, "w").write(donjon_deck())
    a = p + ".access"
    open(a, "w").write(DON_ACCESS)
    os.chmod(a, 0o755)
    subprocess.run([os.path.join(ROOT, "tools", "link_decks.sh")],
                   check=True, capture_output=True)
    run = os.path.join(ROOT, "5.1", "Donjon")
    res = os.path.join(run, "Linux_aarch64", name + ".don.result")
    if os.path.exists(res):
        os.remove(res)
    subprocess.run(["./rdonjon", name + ".don"], cwd=run, check=True,
                   capture_output=True)

    # two INTG blocks: the 25-cell supercell, then the 1-cell reference
    blocks, cur, grp = [], None, None
    for ln in open(res, errors="replace"):
        if "OUTAUX: REACTION RATE CALCULATION" in ln:
            cur = {}
            blocks.append(cur)
            continue
        g = a64b.GRP.match(ln)
        if g:
            grp = int(g.group(1))
            continue
        m = a64b.ROW.match(ln)
        if m and cur is not None:
            c = ln.split()
            # OUT: INTG prints RATES, not cross sections: column 3 is the
            # zone's integral of Sigma*phi and column 2 is its integral of
            # phi.  Dividing recovers the flux-weighted cross section, which
            # is the quantity that is a property of the material rather than
            # of the flux shape.  Verified against a64b: the same mixture
            # read through both pipelines gives 0.3665 vs 0.3664 after the
            # division, and 6.018 vs 2.016 before it.
            phi = float(c[2])
            cur[(int(c[0]), grp)] = (float(c[3]) / phi, float(c[4]) / phi)
    if len(blocks) != 2:
        sys.exit(f"sup5: expected 2 INTG blocks, got {len(blocks)} -- see {res}")
    s5, ref = blocks
    cnt = ring_counts()

    def pert(m, g, k):
        a = s5[(m, g)][k]
        b = ref[(1, g)][k]
        return 100.0 * (a - b) / b

    groups = {}
    for (i, j), v in cnt.items():
        groups.setdefault(v, []).append(i * N + j + 1)

    print(f"\nPerturbation of the fuel cell's two-group constants against the "
          f"infinite lattice, %\n(NTOT0; {N}x{N} supercell, CPS at {CPS_AT}, "
          f"centre type {STYPE}, fresh fuel, dca 0.72)\n")
    print(f"  {'ring (orth,diag)':>18} {'n':>3} {'group 1':>22} {'group 2':>22}")
    res_by = {}
    for v in sorted(groups, key=lambda t: (t[0] + t[1], t)):
        ms = groups[v]
        out = []
        for g in (1, 2):
            vals = [pert(m, g, 0) for m in ms]
            out.append((sum(vals) / len(vals), max(vals) - min(vals)))
        res_by[v] = [o[0] for o in out]
        print(f"  {str(v):>18} {len(ms):3d} "
              f"{out[0][0]:+10.4f} (spread {out[0][1]:6.4f}) "
              f"{out[1][0]:+10.4f} (spread {out[1][1]:6.4f})")

    # The superposition test is on the INCREMENT above the zero-ring cells,
    # not on the raw perturbation.  A cell with nothing in its eight-ring is
    # still two cells from a rod, and with a migration length of order a metre
    # -- four cell pitches -- that is not an unperturbed cell.  The zero-ring
    # value is the common baseline; what has to add up is what sits above it.
    base, one, two = res_by.get((0, 0)), res_by.get((0, 1)), res_by.get((0, 2))
    print("\n  SUPERPOSITION TEST -- is the increment for 2 diagonal "
          "neighbours twice the increment for 1?")
    if base and one and two:
        for g in (0, 1):
            d1, d2 = one[g] - base[g], two[g] - base[g]
            pred = 2.0 * d1
            r = d2 / pred if abs(pred) > 1e-9 else float("nan")
            print(f"    group {g+1}: baseline (0 in ring) {base[g]:+8.4f}"
                  f"   d(1 diag) {d1:+8.4f}   d(2 diag) {d2:+8.4f}"
                  f"   predicted {pred:+8.4f}   ratio {r:6.3f}")
        print("\n    Additive if the ratios sit near 1.0.  Well below 1 means"
              "\n    the perturbation saturates and a linear environment axis"
              "\n    will overcount; well above 1 means it compounds.")
    print("\n  HOW FAR DOES IT REACH?  The zero-ring baseline above is the")
    print("  answer: it is the perturbation of a cell with NO CPS neighbour,")
    print("  measured against a true infinite lattice.  If it is comparable to")
    print("  the one-neighbour increment, an eight-ring descriptor is too")
    print("  short-ranged and the axis needs a wider stencil.")
    print("\n  The replicate spreads above are the internal consistency check:")
    print("  cells with identical environments must agree, and they are not")
    print("  constrained to -- nothing in the calculation imposes the symmetry.")


# ---------------------------------------------------------------------------
# Part 2: the SPH factors, which is where the environment effect actually lives
# ---------------------------------------------------------------------------

SPH_RESULT = os.path.join(ROOT, "5.1", "Dragon", "Linux_aarch64",
                          "rbmk_cps_sup5sph.result")


def sph_factors(path=SPH_RESULT):
    """The converged SPH factors of the 5 x 5, from rbmk_cps_sup5sph.x2m."""
    f = {}
    for m, g, v in re.findall(r"SPH\(\s*(\d+),\s*(\d+)\)=\s*([\d.]+)",
                              open(path, errors="replace").read()):
        f[(int(m), int(g))] = float(v)      # later tables overwrite earlier
    if len(f) != NM * 2:
        sys.exit(f"sup5: parsed {len(f)} SPH factors, expected {NM * 2}")
    return f


def torus(a, b):
    """Distance on the periodic 5 x 5, in cell pitches."""
    d = [min(abs(a[k] - b[k]), N - abs(a[k] - b[k])) for k in (0, 1)]
    return math.hypot(*d)


def analyse_sph():
    f = sph_factors()
    cnt = ring_counts()
    print("SPH factor map, group 1   (R marks a CPS channel)\n")
    for i in range(N):
        print("   " + "".join(
            (f" R{f[(i*N+j+1,1)]:5.2f}" if (i, j) in CPS_AT
             else f"  {f[(i*N+j+1,1)]:5.2f}") for j in range(N)))

    rows = []
    for (i, j), rc in sorted(cnt.items()):
        m = i * N + j + 1
        ds = [torus((i, j), c) for c in CPS_AT]
        rows.append(dict(cell=(i, j), m=m, ring=rc, dnear=min(ds),
                         inv=sum(1.0 / d ** 2 for d in ds),
                         g1=f[(m, 1)], g2=f[(m, 2)]))

    print(f"\n{'cell':>7} {'mix':>4} {'ring(o,d)':>10} {'d_near':>7} "
          f"{'sum 1/d^2':>10} {'SPH g1':>8} {'SPH g2':>8}")
    for r in sorted(rows, key=lambda r: (r["dnear"], r["inv"])):
        print(f"{str(r['cell']):>7} {r['m']:4d} {str(r['ring']):>10} "
              f"{r['dnear']:7.3f} {r['inv']:10.4f} {r['g1']:8.5f} {r['g2']:8.5f}")

    # Which environment descriptor actually determines the factor?  A good one
    # puts cells with equal descriptor at equal SPH; the within-class spread is
    # the whole test, and nothing in the calculation imposes it.
    print(f"\n  {'descriptor':>14} {'classes':>8} {'worst within-class spread':>27}")
    for name, key in (("eight-ring", lambda r: sum(r["ring"])),
                      ("nearest d", lambda r: round(r["dnear"], 3)),
                      ("sum 1/d^2", lambda r: round(r["inv"], 3))):
        cls = {}
        for r in rows:
            cls.setdefault(key(r), []).append(r["g1"])
        w = max(max(v) - min(v) for v in cls.values())
        print(f"  {name:>14} {len(cls):8d} {w:27.4f}")
    span = max(r["g1"] for r in rows) - min(r["g1"] for r in rows)
    print(f"\n  total span of the fuel-cell factors, group 1: {span:.4f}")
    print("  (the core discards all of these and uses 1.0 for every fuel cell)")


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "write"
    {"write": write, "analyse": analyse, "sph": analyse_sph}[cmd]()
