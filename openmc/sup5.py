NM = N * N


def donjon_deck():
    """Read the 5 x 5 COMPO's 25 cells and the fuel COMPO's single cell, and
    print both through OUT: INTG MIX so the comparison runs through one path.

    The 5 x 5 geometry here is only a carrier for OUT:'s macro-zones -- the
    cross sections are what is being read, not a flux solution worth trusting.
    Mixture 26 is the infinite-lattice reference, placed in a cell of its own.
    """
    grid = "\n".join("  " + " ".join(f"{i*N+j+1:3d}" for j in range(N))
                     for i in range(N))
    s5 = "\n".join(
        f"  MIX {m} FROM {m} SET 'burnup' 0.0 SET 'DCA' 0.72 ENDMIX"
        for m in range(1, NM + 1))
    mesh = " ".join(f"{25.0*i:.1f}" for i in range(N + 1))
    return f"""*----
*  A6.4 SUPERPOSITION READ-OUT.  GENERATED by openmc/sup5.py.
*  Prints the {NM} cell constants of the {N}x{N} supercell and, separately, the
*  infinite-lattice fuel cell from the fuel COMPO, through the same OUT: path.
*----
LINKED_LIST SCpo FCpo MS5 MREF OUTM GEOM GEOR TRACK TRKR SYSTEM FLUX ;
SEQ_ASCII   _CCompoS5 :: FILE './_CCompoS5' ;
SEQ_ASCII   _ACompo   :: FILE './_ACompo' ;
MODULE      NCR: GEO: TRIVAT: TRIVAA: FLUD: OUT: GREP: DELETE: END: ;
REAL kk ;
SCpo := _CCompoS5 ;
FCpo := _ACompo ;

GEOM := GEO: :: CAR2D {N} {N}
  X- REFL X+ REFL Y- REFL Y+ REFL
  MESHX {mesh} MESHY {mesh}
  MIX
{grid}
  ;
TRACK := TRIVAT: GEOM :: EDIT 0 MAXR 40 DUAL 1 1 ;
MS5 := NCR: SCpo :: EDIT 0 MACRO LINEAR NMIX {NM}
  COMPO SCpo 'EDIS5'
{s5}  ;
SYSTEM := TRIVAA: MS5 TRACK :: EDIT 0 ;
FLUX := FLUD: SYSTEM TRACK :: EDIT 0 EXTE 1.0E-7 ;
GREP: FLUX :: GETVAL 'K-EFFECTIVE' 1 >>kk<< ;
ECHO "SUP5OUT S5" kk ;
OUTM := OUT: FLUX TRACK MS5 GEOM :: EDIT 2 INTG MIX ;
OUTM SYSTEM FLUX := DELETE: OUTM SYSTEM FLUX ;

*--- the infinite-lattice reference, on its own one-cell geometry
GEOR := GEO: :: CAR2D 1 1
  X- REFL X+ REFL Y- REFL Y+ REFL
  MESHX 0.0 25.0 MESHY 0.0 25.0
  MIX 1 ;
TRKR := TRIVAT: GEOR :: EDIT 0 MAXR 4 DUAL 1 1 ;
MREF := NCR: FCpo :: EDIT 0 MACRO LINEAR NMIX 1
  COMPO FCpo 'EDIRBMK'
  MIX 1 FROM 1 SET 'burnup' 0.0 SET 'DCA' 0.72 SET 'TF' 900.0
        SET 'TG' 750.0 ENDMIX ;
SYSTEM := TRIVAA: MREF TRKR :: EDIT 0 ;
FLUX := FLUD: SYSTEM TRKR :: EDIT 0 EXTE 1.0E-7 ;
GREP: FLUX :: GETVAL 'K-EFFECTIVE' 1 >>kk<< ;
ECHO "SUP5OUT REF" kk ;
OUTM := OUT: FLUX TRKR MREF GEOR :: EDIT 2 INTG MIX ;

ECHO "rbmk_cps_sup5_out completed" ;
END: ;
QUIT .
"""


DON_ACCESS = """#!/bin/sh
src="$1"/../Dragon/compo
cp "$src"/_CCompoS5 . || exit 1
cp "$src"/_ACompo . || exit 1
"""


def analyse():
    import a64b
    name = "rbmk_cps_sup5_out"
    p = os.path.join(DON, name + ".don")
    open(p, "w").write(donjon_deck())
    a = p + ".access"
    open(a, "w").write(DON_ACCESS)
    os.chmod(a, 0o755)
    subprocess.run([os.path.join(ROOT, "tools", "link_decks.sh")],
                   check=True, capture_output=True)
    run = os.path.join(ROOT, "5.1", "Donjon")
    res = os.path.join(run, "Linux_aarch64", name + ".don.result")
    if os.path.exists(res):
        os.remove(res)
    subprocess.run(["./rdonjon", name + ".don"], cwd=run, check=True,
                   capture_output=True)

    # two INTG blocks: the 25-cell supercell, then the 1-cell reference
    blocks, cur, grp = [], None, None
    for ln in open(res, errors="replace"):
        if "REACTION RATE CALCULATION" in ln:
            cur = {}
            blocks.append(cur)
            continue
        g = a64b.GRP.match(ln)
        if g:
            grp = int(g.group(1))
            continue
        m = a64b.ROW.match(ln)
        if m and cur is not None:
            c = ln.split()
            cur[(int(c[0]), grp)] = (float(c[3]), float(c[4]))   # NTOT0, SIGW00
    if len(blocks) != 2:
        sys.exit(f"sup5: expected 2 INTG blocks, got {len(blocks)} -- see {res}")
    s5, ref = blocks
    cnt = ring_counts()

    def pert(m, g, k):
        a = s5[(m, g)][k]
        b = ref[(1, g)][k]
        return 100.0 * (a - b) / b

    groups = {}
    for (i, j), v in cnt.items():
        groups.setdefault(v, []).append(i * N + j + 1)

    print(f"\nPerturbation of the fuel cell's two-group constants against the "
          f"infinite lattice, %\n(NTOT0; {N}x{N} supercell, CPS at {CPS_AT}, "
          f"centre type {STYPE}, fresh fuel, dca 0.72)\n")
    print(f"  {'ring (orth,diag)':>18} {'n':>3} {'group 1':>22} {'group 2':>22}")
    res_by = {}
    for v in sorted(groups, key=lambda t: (t[0] + t[1], t)):
        ms = groups[v]
        out = []
        for g in (1, 2):
            vals = [pert(m, g, 0) for m in ms]
            out.append((sum(vals) / len(vals), max(vals) - min(vals)))
        res_by[v] = [o[0] for o in out]
        print(f"  {str(v):>18} {len(ms):3d} "
              f"{out[0][0]:+10.4f} (spread {out[0][1]:6.4f}) "
              f"{out[1][0]:+10.4f} (spread {out[1][1]:6.4f})")

    # The superposition test is on the INCREMENT above the zero-ring cells,
    # not on the raw perturbation.  A cell with nothing in its eight-ring is
    # still two cells from a rod, and with a migration length of order a metre
    # -- four cell pitches -- that is not an unperturbed cell.  The zero-ring
    # value is the common baseline; what has to add up is what sits above it.
    base, one, two = res_by.get((0, 0)), res_by.get((0, 1)), res_by.get((0, 2))
    print("\n  SUPERPOSITION TEST -- is the increment for 2 diagonal "
          "neighbours twice the increment for 1?")
    if base and one and two:
        for g in (0, 1):
            d1, d2 = one[g] - base[g], two[g] - base[g]
            pred = 2.0 * d1
            r = d2 / pred if abs(pred) > 1e-9 else float("nan")
            print(f"    group {g+1}: baseline (0 in ring) {base[g]:+8.4f}"
                  f"   d(1 diag) {d1:+8.4f}   d(2 diag) {d2:+8.4f}"
                  f"   predicted {pred:+8.4f}   ratio {r:6.3f}")
        print("\n    Additive if the ratios sit near 1.0.  Well below 1 means"
              "\n    the perturbation saturates and a linear environment axis"
              "\n    will overcount; well above 1 means it compounds.")
    print("\n  HOW FAR DOES IT REACH?  The zero-ring baseline above is the")
    print("  answer: it is the perturbation of a cell with NO CPS neighbour,")
    print("  measured against a true infinite lattice.  If it is comparable to")
    print("  the one-neighbour increment, an eight-ring descriptor is too")
    print("  short-ranged and the axis needs a wider stencil.")
    print("\n  The replicate spreads above are the internal consistency check:")
    print("  cells with identical environments must agree, and they are not")
    print("  constrained to -- nothing in the calculation imposes the symmetry.")
