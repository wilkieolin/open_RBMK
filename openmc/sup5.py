#!/usr/bin/env python3
"""Superposition test: does a fuel cell's environment perturbation add up?

WHY THIS DECIDES THE SCOPE OF A6.4.  A6.4b is dead (PROGRESS.md, 2026-09-30):
no rod-only SPH factor closes the gate, because the error lives in the eight
fuel cells around the rod, which differ from infinite-lattice fuel by a few
per cent.  The surviving fix is to make the fuel cross sections depend on the
local CPS environment.  Whether that is days of work or weeks turns on one
question:

    is the perturbation ADDITIVE in the number of CPS neighbours?

If yes, environment is a CONTINUOUS axis -- something like the CPS count in
the eight-ring -- which interpolates, handles rods moving mid-transient, and
needs only a handful of supercell calculations.  If no, it has to be discrete
classes enumerated by configuration, and the cost goes up an order of
magnitude.

THE DESIGN.  One 5 x 5 supercell with TWO CPS channels, at (1,1) and (3,3) in
a 0-based periodic 5 x 5.  That single geometry contains fuel cells with 0, 1
and 2 CPS channels in their eight-ring, so the comparison is internal: same
library, same state, same tracking, same fuel.  Nothing is differenced across
runs that were set up separately.

    (0,0)  1 CPS, diagonal          (1,2)  1 CPS, orthogonal
    (2,2)  2 CPS, both diagonal     (1,3)  0 CPS in the ring
    CPS fraction 2/25 = 8 %, against Unit 4's 227/1888 = 12 %

The infinite-lattice reference is the ordinary RbmkGeo cell, computed in the
SAME deck at the same state, so the perturbation is a clean ratio.

WHY THE CPS CHANNELS SIT ON THE DIAGONAL.  EDI: MERG CELL numbers its merged
regions cell by cell, and the 3 x 3 deck dodges the row-major/column-major
question only because its single centre cell is region 5 either way.  A 5 x 5
cannot dodge it -- except that {(1,1), (3,3)} is symmetric under transpose, so
every cell (i,j) has the same CPS environment as (j,i).  The classification is
therefore invariant to the raster order, and a wrong guess about it cannot
corrupt the result.  That is the reason for this placement, not aesthetics.

Fresh fuel only.  A6.4 item 3 showed the whole effect is present at zero
burnup, so depletion would add an hour and nothing else.
"""
import os
import re
import subprocess
import sys

import cps_common as cc

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = cc.ROOT
DATA = cc.DATA
PROC = cc.PROC
DON = cc.DON

N = 5
CPS_AT = [(1, 1), (3, 3)]          # 0-based (row, col)
STYPE = "ABS"                      # strongest perturbation: best signal


def ring_counts():
    """CPS channels in each fuel cell's eight-ring, under 5 x 5 periodicity."""
    cps = set(CPS_AT)
    out = {}
    for i in range(N):
        for j in range(N):
            if (i, j) in cps:
                continue
            e = sum(1 for d in ((1, 0), (-1, 0), (0, 1), (0, -1))
                    if ((i + d[0]) % N, (j + d[1]) % N) in cps)
            c = sum(1 for d in ((1, 1), (1, -1), (-1, 1), (-1, -1))
                    if ((i + d[0]) % N, (j + d[1]) % N) in cps)
            out[(i, j)] = (e, c)
    return out


def geo_proc():
    """RbmkSc5<type>.c2m -- the 5 x 5, built from cps_common's own cell blocks."""
    cells = [["F"] * N for _ in range(N)]
    for i, j in CPS_AT:
        cells[i][j] = "C"
    rows = "\n       ".join(" ".join(r) for r in cells)
    ks = sorted({s for _, _, s in cc.SECTIONS.get(STYPE, [])} | {1, 2, 3, 4, 6})

    def geo(split):
        fsplit = "    SPLITR <<k4>> <<k1>> <<k1>> <<k2>> <<k6>>\n" if split else ""
        csplit = "SPLITR <<k1>> <<k1>> <<k1>> " if split else ""
        rsplit = "SPLITR <<k1>> <<k3>> <<k1>> <<k1>> " if split else ""
        body = cc.FUEL_CELL.format(fsplit=fsplit, csplit=csplit, rsplit=rsplit)
        body += "\n" + cc._cps_cell(STYPE, split)
        return f"""GEO: :: CAR2D {N} {N}
  EDIT 0
  X- REFL X+ REFL Y- REFL Y+ REFL
  CELL {rows}
{body}
  ;"""
    kdecl = "\n".join(f"INTEGER k{s} := {s} k * ;" for s in ks)
    cnt = ring_counts()
    note = "\n".join(
        f"*    cell {i},{j} (mix {i*N+j+1:2d}): {e} orthogonal, {c} diagonal"
        for (i, j), (e, c) in sorted(cnt.items()))
    return f"""*DECK RbmkSc5{STYPE}
*----
*  {N} x {N} CPS supercell, centre type {STYPE}, CPS at {CPS_AT}.
*  GENERATED by openmc/sup5.py -- edit that, not this file.
*  The fuel cell and the CPS cell are cps_common's, byte for byte the ones the
*  3 x 3 supercell uses, so the two geometries differ only in layout.
*
*  CPS channels in each fuel cell's eight-ring (periodic):
{note}
*----
PARAMETER GEOSS GEOFL ::
   EDIT 0
      ::: LINKED_LIST GEOSS GEOFL ;
;
MODULE GEO: END: ;
INTEGER k ;
:: >>k<< ;
{kdecl}

GEOSS := {geo(False)}

GEOFL := {geo(True)}

END: ;
QUIT .
"""


def dragon_deck():
    """One state, no depletion.  EDI: MERG CELL -> 25 cells, stored in a COMPO.

    NO SPH.  The question here is what the raw homogenisation does, and an SPH
    normalisation would smear the answer across the cells -- which is exactly
    the trap noted against reading the 3 x 3's per-cell numbers as physics
    (ASYM 1 pins the corner, so its factor absorbs none of the difference and
    its neighbours' factors absorb some of theirs).
    """
    grid = "\n".join("  " + " ".join(f"{i*N+j+1:3d}" for j in range(N))
                     for i in range(N))
    return f"""*----
*  A6.4 SUPERPOSITION TEST -- {N} x {N} supercell, {len(CPS_AT)} CPS channels.
*  GENERATED by openmc/sup5.py.  Edit the generator, not this file.
*
*  Fresh fuel, dca 0.72, TF 900 K: one state.  A6.4 item 3 established the
*  whole neighbour effect is present at zero burnup, so depletion would cost
*  an hour and change nothing.
*
*  Also computes the ORDINARY single cell in the same deck, at the same state
*  with the same library and tracking, as the infinite-lattice reference.
*
*  Output: SUP5 <mix> <k-inf>, and the per-cell constants via the COMPO.
*----
LINKED_LIST LIBRARY LIBSS GEOSS GEOFL TRKSS TRK SYS FLUX EDIOBJ
            CGEOSS CGEOFL CTRKSS CTRK CSYS CFLUX GEOMAC COMPO ;
SEQ_BINARY  FTRKSS FTRK CFTRKSS CFTRK ;
SEQ_ASCII   _CCompoS5 :: FILE './_CCompoS5' ;
MODULE      LIB: GEO: NXT: USS: ASM: FLU: EDI: COMPO: GREP: DELETE: END: ;
PROCEDURE   RbmkLib RbmkGeo RbmkCpsLib RbmkSc5{STYPE} ;
REAL tgnom := 750.0 ;
REAL tcool := 573.0 ;
REAL kinf kcell ;

*--- the infinite-lattice single cell.  Its k-inf is a consistency check that
*    this deck's library and tracking reproduce the basis the fuel COMPO was
*    built on; the reference CROSS SECTIONS come from _ACompo in the DONJON
*    step, which is the same cell and what the core actually uses.
CGEOSS CGEOFL := RbmkGeo ;
CTRKSS CFTRKSS := NXT: CGEOSS :: EDIT 0 TITLE 'C-SS' ALLG BATCH 100 TISO 8 15.0 ;
CTRK CFTRK := NXT: CGEOFL :: EDIT 0 TITLE 'C-FL' ALLG BATCH 100 TISO 15 30.0 ;
LIBRARY := RbmkLib :: 0.72 900.0 <<tgnom>> <<tcool>> ;
LIBSS := USS: LIBRARY CTRKSS CFTRKSS :: EDIT 0 PASS 2 MAXST 300 ;
CSYS := ASM: LIBSS CTRK CFTRK :: EDIT 0 ;
CFLUX := FLU: LIBSS CTRK CSYS :: TYPE K B1 SIGS BUCK 0.0 EXTE 1.0E-6 ;
GREP: CFLUX :: GETVAL 'K-INFINITY' 1 >>kcell<< ;
ECHO "SUP5CELL kinf=" kcell ;
LIBRARY LIBSS CSYS CFLUX := DELETE: LIBRARY LIBSS CSYS CFLUX ;

*--- the {N} x {N} supercell
GEOSS GEOFL := RbmkSc5{STYPE} :: 1 ;
TRKSS FTRKSS := NXT: GEOSS :: EDIT 0 TITLE 'S5-SS' ALLG BATCH 100 TISO 8 15.0 ;
TRK FTRK := NXT: GEOFL :: EDIT 0 TITLE 'S5-FL' ALLG BATCH 100 TISO 15 30.0 ;
LIBRARY := RbmkLib :: 0.72 900.0 <<tgnom>> <<tcool>> ;
LIBRARY := RbmkCpsLib LIBRARY ::
  {cc.B4C_DENSITY['nom']} {cc.DSP_DENSITY['nom']} {cc.T_DSP} {cc.T_CPS} ;
LIBSS := USS: LIBRARY TRKSS FTRKSS :: EDIT 0 PASS 2 MAXST 300 ;
SYS := ASM: LIBSS TRK FTRK :: EDIT 0 ;
FLUX := FLU: LIBSS TRK SYS :: TYPE K B1 SIGS BUCK 0.0 EXTE 1.0E-6 ;
GREP: FLUX :: GETVAL 'K-INFINITY' 1 >>kinf<< ;
ECHO "SUP5 kinf=" kinf ;

GEOMAC := GEO: :: CAR2D {N} {N}
  X- REFL X+ REFL Y- REFL Y+ REFL
  MESHX 0.0 25.0 50.0 75.0 100.0 125.0
  MESHY 0.0 25.0 50.0 75.0 100.0 125.0
  MIX
{grid}
  ;
EDIOBJ := EDI: LIBSS TRK FLUX GEOFL SYS GEOMAC ::
  EDIT 0 MERG CELL NXT COND 0.625 GOLVER MGEO GEOMAC SAVE ON EDIS5 ;

COMPO := COMPO: ::
  EDIT 1 STEP UP 'EDIS5' MAXCAL 3
  COMM 'A6.4 superposition test, {N}x{N}, CPS at {CPS_AT}' ENDC
  PARA 'burnup' IRRA
  PARA 'DCA' VALU REAL
  INIT ;
COMPO := COMPO: COMPO EDIOBJ LIBRARY ::
  EDIT 0 STEP UP 'EDIS5' 'DCA' 0.72 SET 0.0 DAY ;
_CCompoS5 := COMPO ;

ECHO "rbmk_cps_sup5 completed" ;
END: ;
QUIT .
"""


def write():
    open(os.path.join(PROC, f"RbmkSc5{STYPE}.c2m"), "w").write(geo_proc())
    p = os.path.join(DATA, "rbmk_cps_sup5.x2m")
    open(p, "w").write(dragon_deck())
    a = os.path.join(DATA, "rbmk_cps_sup5.access")
    if os.path.lexists(a):
        os.remove(a)
    os.symlink("../../common/rbmk.access", a)
    sv = os.path.join(DATA, "rbmk_cps_sup5.save")
    open(sv, "w").write("#!/bin/sh\ncp _CCompoS5 \"$1\"/../Dragon/compo/ 2>/dev/null\n")
    os.chmod(sv, 0o755)
    for f in (os.path.join(PROC, f"RbmkSc5{STYPE}.c2m"), p):
        over = [i + 1 for i, l in enumerate(open(f).read().splitlines()) if len(l) > 120]
        if over:
            sys.exit(f"sup5: {f} lines over 120 columns: {over[:5]}")
    print("wrote", os.path.relpath(p, ROOT))
    print("ring counts (orthogonal, diagonal):")
    for (i, j), v in sorted(ring_counts().items()):
        print(f"   cell {i},{j}  mix {i*N+j+1:2d}  {v}")


if __name__ == "__main__":
    write()


