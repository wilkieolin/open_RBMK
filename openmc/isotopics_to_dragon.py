"""Hand OpenMC's depleted fuel to DRAGON at fixed composition (METHOD_CONVERGENCE_PLAN B1, H10).

    python isotopics_to_dragon.py <bu MWd/kg> [<bu> ...]

For each burnup, reads the fuel of materials 6 (inner ring) and 7 (outer ring)
from OpenMC's depletion (RBMK_DEPLDIR, default depl_gb10) and writes
decks/Dragon/data/rbmk_proc/RbmkLibOMC<bu>.c2m: RbmkLibZ.c2m with MIX 6 and MIX 7
replaced by those isotopics.  Everything else -- the non-fuel mixtures, the
self-shielding sets, CTRA/ANIS -- is RbmkLibZ's, so the matching DRAGON deck
(rbmk_meth_omc<bu>, from gen_meth.py) differs from buzr361's branch at that
burnup only in where the fuel composition came from:

    DRAGON(own depletion) - DRAGON(OpenMC fuel)  = depletion-trajectory effect
    DRAGON(OpenMC fuel)   - OpenMC               = transport effect

U-235 and U-238 keep their self-shielding sets (1 inner, 2 outer), as in the
production library; every other nuclide is unshielded, as in the burnup deck
(H8 showed shielding the Pu isotopes is worth <= 3 pcm).  Nuclides OpenMC
carries but the draglib lacks are dropped and listed, heaviest first.
"""
import glob
import os
import re
import sys

import openmc.deplete

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PROC = os.path.join(ROOT, "decks", "Dragon", "data", "rbmk_proc")
DEPLDIR = os.environ.get("RBMK_DEPLDIR", "depl_gb10")
DRAGLIB = "draglibendfb8r1SHEM361_v5p1"
# The grid deplete_void.py saves (its substeps() marks): burnup -> result index.
BU_GRID = [0.0, 2.0, 5.0, 10.0, 15.0, 20.0]
SETS = {6: 1, 7: 2}


def library_names():
    """Isotope names in the draglib: each record is tagged '<name> from /tmp/<build>'."""
    f = sorted(glob.glob(os.path.join(ROOT, ".cache", "draglib", DRAGLIB + ".*")))
    if not f:
        sys.exit(f"no decompressed {DRAGLIB} in .cache/draglib; run any SHEM-361 deck first")
    data = open(f[0], "rb").read()
    return {m.decode() for m in re.findall(rb"([A-Z][a-z]?\d{1,3}m?(?:_\w+)?) from /tmp/", data)}


def dragon_name(n):
    return n.replace("_m1", "m")


def result_index(bu):
    from deplete_void import substeps
    marks = substeps()[1]
    return marks[BU_GRID.index(bu)]


def fuel_block(mid, mat, lib, dropped):
    ring = "inner ring (6 rods)" if mid == 6 else "outer ring (12 rods)"
    lines = [f"* MIX {mid}: UO2 fuel, {ring}, OpenMC isotopics", f"  MIX     {mid}  <<tfuel>>"]
    for n, d in sorted(mat.get_nuclide_atom_densities().items(), key=lambda x: -x[1]):
        dn = dragon_name(n)
        if d <= 0:
            continue
        if dn not in lib:
            dropped.append((d, n, mid))
            continue
        ss = f"  {SETS[mid]}" if dn in ("U235", "U238") else ""
        lines.append(f"     {dn:<8s}= {dn:<8s}{d:.5E}{ss}")
    return "\n".join(lines) + "\n"


def main(bus):
    lib = library_names()
    res = openmc.deplete.Results(os.path.join(HERE, DEPLDIR, "depletion_results.h5"))
    src = open(os.path.join(PROC, "RbmkLibZ.c2m")).read()
    start, end = src.index("* MIX 6:"), src.index("* MIX 8:")
    for bu in bus:
        idx = result_index(bu)
        mats = {m.id: m for m in res.export_to_materials(
            idx, path=os.path.join(HERE, DEPLDIR, "materials.xml"))}
        dropped = []
        blocks = "\n".join(fuel_block(mid, mats[mid], lib, dropped) for mid in (6, 7))
        head = (f"*----\n*  GENERATED by openmc/isotopics_to_dragon.py: RbmkLibZ.c2m with the fuel\n"
                f"*  (MIX 6, 7) from OpenMC's depletion at {bu:g} MWd/kg ({DEPLDIR}, result\n"
                f"*  index {idx}).  B1 / H10.  Regenerate, don't edit.\n")
        if dropped:
            dropped.sort(reverse=True)
            tot = sum(d for d, _, _ in dropped)
            head += f"*  Dropped (not in {DRAGLIB}), total {tot:.3E} atom/b-cm:\n"
            for d, n, mid in dropped[:8]:
                head += f"*    {n:<10s} MIX {mid}  {d:.3E}\n"
        head += "*----\n"
        name = f"RbmkLibOMC{bu:g}"
        body = src[:start] + blocks + "\n" + src[end:]
        open(os.path.join(PROC, f"{name}.c2m"), "w").write(head + body)
        fu = {m: sum(d for n, d in mats[m].get_nuclide_atom_densities().items()) for m in (6, 7)}
        print(f"wrote {name}.c2m: {len(dropped)} nuclide entries dropped, "
              f"{sum(d for d, _, _ in dropped) / sum(fu.values()) * 100:.4f} % of fuel atoms")


if __name__ == "__main__":
    main([float(x) for x in sys.argv[1:]])
